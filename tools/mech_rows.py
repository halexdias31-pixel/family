def draw(shape, colour):
    return [r.replace('X', colour) for r in D[shape]]

def write(name, key, rows):
    with open(os.path.join(OUT, name + '.json'), 'w', encoding='utf-8') as fh:
        fh.write('{"' + key + '": [\n' + ',\n'.join(json.dumps(r, ensure_ascii=False) for r in rows) + '\n]}\n')

models = []
for c in CARS:
    r = {k: c[k] for k in ('id', 'make', 'model', 'gen', 'phase', 'market', 'years', 'size', 'valves', 'badge', 'fuel', 'code')}
    r = {k: v for k, v in r.items() if v}
    r['name'] = ' '.join(v for v in (c['make'], c['model'], c['gen'], c['size'], c['badge'] or c['valves']) if v)
    r['source'] = c['source']
    r['px'] = draw('car', c['body'])
    models.append(r)
parts = []
for i, (name, system, value, rule, shape, colour, does) in enumerate(PARTS):
    fits = [c['code'] for c in CARS if RULES[rule](c)]
    parts.append(dict(id='MP-%03d' % (i + 1), name=name, system=system, does=does, value=value, fits=fits, source=PRICE_SRC, px=draw(shape, colour)))
pc = []
for i, (name, typ, socket, iface, links, shape, colour, does) in enumerate(PC):
    pc.append(dict(id='PC-%03d' % (i + 1), name=name, type=typ, socket=socket, iface=iface, links=links, does=does, source=PC_SRC, px=draw(shape, colour)))
write('models', 'models', models)
write('parts', 'parts', parts)
write('pc', 'pc', pc)
print('mech_rows: %d cars, %d parts, %d PC parts' % (len(models), len(parts), len(pc)))
