def plain(html):
    return ' '.join(re.sub(r'<[^>]+>', ' ', html or '').split())


def rewrite(rid, ans):
    """The new answer, or None when this row is already in shape."""
    if rid in SPLIT:
        pre, sep = SPLIT[rid]
        if ans.startswith(pre + DASH):
            return None
        assert ans.startswith(pre + sep), '%s no longer starts %r + %r' % (rid, pre, sep)
        return pre + DASH + ans[len(pre) + len(sep):]
    head = LEAD[rid]
    if ans.startswith(head + DASH):
        return None
    return head + DASH + ans


def answer_span(line):
    """Where the JSON string that is this line's `answer` value starts and ends."""
    k = line.index('"answer":')
    i = k + len('"answer":')
    while line[i] == ' ':
        i += 1
    assert line[i] == '"'
    _, end = json.JSONDecoder().raw_decode(line, i)
    return i, end


def main():
    dry = '--dry' in sys.argv
    lines = FILE.read_text().rstrip('\n').split('\n')
    assert lines[0] == '[' and lines[-1] == ']'
    want = set(SPLIT) | set(LEAD)
    assert not (set(SPLIT) & set(LEAD)), 'a row in both tables'
    seen, out, done, already = set(), [], [], 0
    for line in lines:
        if '"row_id"' not in line:
            out.append(line)
            continue
        row = json.loads(line.rstrip(','))
        rid = row['row_id']
        if rid not in want:
            out.append(line)
            continue
        seen.add(rid)
        new = rewrite(rid, row['answer'])
        if new is None:
            already += 1
            out.append(line)
            continue
        a, b = answer_span(line)
        old_lit = line[a:b]
        ascii_only = '\\u' in old_lit
        lit = json.dumps(new, ensure_ascii=ascii_only)
        nl = line[:a] + lit + line[b:]
        back = json.loads(nl.rstrip(','))
        assert back['answer'] == new
        assert {k: v for k, v in back.items() if k != 'answer'} == {k: v for k, v in row.items() if k != 'answer'}, rid
        out.append(nl)
        done.append((rid, 'SPLIT' if rid in SPLIT else 'LEAD', new.split(DASH)[0]))
    lost = want - seen
    assert not lost, 'no such rows: %r' % sorted(lost)
    for rid, how, head in done:
        print('%-30s %-5s %s' % (rid, how, plain(head)))
    print('%d answers rewritten (%d split where the result already led, %d given a result to lead '
          'with); %d already in shape' % (len(done), sum(1 for d in done if d[1] == 'SPLIT'),
                                          sum(1 for d in done if d[1] == 'LEAD'), already))
    if not dry:
        FILE.write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
