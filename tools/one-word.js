#!/usr/bin/env node
/* @family. — tools/one-word.js THE ONE-WORD CHECK (rule 1.75, unify batch 6 lane B; UNIFY NEXT 4): every word a child or parent reads is a key in
   data/settings/words.json, the one phrasebook, read through text_(key). It fails the build when
   (1) one phrase is written under two keys (trailing stops and spaces aside) — merge them and keep the old key in `aliases`;
   (2) a string literal in js/ or backend/*.gs equals a words.json value — 12+ characters, or one of the SHORT phrases — outside a generated
       file or BEGIN…END block: the same text written twice. OWED lists the other lanes' files still to do; printed as owed. */
'use strict';
const SD = require('./lib/site-data.js');
const fs = require('fs'), path = require('path');
const { bare } = require('./lib/gen.js');
const ROOT = path.join(__dirname, '..');
const MIN = +process.env.ONE_WORD_MIN || 12; // 12+ characters: shorter words (Open, Tutor) are too often data
const SHORT = ['save', 'saved', 'try-again']; // short words read from the phrasebook all the same; "Saved." counts as "Saved"
const OWED = []; // every lane's files paid up (UNIFY NEXT 4); a file named here is printed as owed, not failed
/* TWO KEYS, ONE PHRASE, ON PURPOSE: the sentence (more is added after it) and the label that stands alone. */
const KEEP = { 'no-free-hours-this-week-2': 'no-free-hours-this-week' };
/* A PHRASE THAT IS ALSO A STORED VALUE (a sheet cell the backend writes and matches) stays a literal in backend/: changing the word must not change the data. */
const STORED = { 'shared-with-tutor': 'backend/' };
const norm = s => s.replace(/[.\s]+$/, '');

/* (1) ONE PHRASE, ONE KEY. */
function twice() {
  const words = SD.words(), seen = new Map(), bad = [];
  for (const [k, v] of Object.entries(words)) {
    if (typeof v !== 'string' || !norm(v)) continue;
    const n = norm(v), was = seen.get(n);
    if (was == null) seen.set(n, k);
    else if (KEEP[k] !== was && KEEP[was] !== k) bad.push(JSON.stringify(v) + ' is under ' + was + ' and ' + k);
  }
  return bad;
}

/* (2) NO COPY OUTSIDE IT. COMMENTS BLANKED (strings kept) by gen.js bare, so a word quoted in a comment is not a second copy. */
function scan() {
  const words = SD.words();
  const byText = new Map();
  for (const [k, v] of Object.entries(words)) if (typeof v === 'string' && v.length >= MIN && !byText.has(v)) byText.set(v, k);
  for (const k of SHORT) if (typeof words[k] === 'string') { byText.set(words[k], k); byText.set(words[k] + '.', k); }
  const hits = [];
  const files = fs.readdirSync(path.join(ROOT, 'js')).filter(f => f.endsWith('.js')).map(f => 'js/' + f)
    .concat(fs.readdirSync(path.join(ROOT, 'backend')).filter(f => f.endsWith('.gs')).map(f => 'backend/' + f)).sort();
  for (const rel of files) {
    const raw = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    if (/^\/\*[^\n]*(WRITTEN BY tools\/|GENERATED by)/.test(raw)) continue; // a generated file is its json's copy
    const src = bare(raw, { generated: true, comments: 'js' });
    const f = path.basename(rel);
    src.split('\n').forEach((line, i) => {
      const re = /'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"|`((?:[^`\\$]|\\.)*)`/g; let m;
      while ((m = re.exec(line))) {
        let s = m[1] != null ? m[1] : m[2] != null ? m[2] : m[3];
        try { s = JSON.parse('"' + s.replace(/\\'/g, "'").replace(/"/g, '\\"').replace(/\\\\"/g, '\\"') + '"'); } catch (e) {}
        if (byText.has(s) && !(STORED[byText.get(s)] && rel.startsWith(STORED[byText.get(s)]))) hits.push({ f, rel, line: i + 1, key: byText.get(s), s });
      }
    });
  }
  return hits;
}

async function run() {
  const dup = twice();
  if (dup.length) {
    dup.forEach(d => console.log('  ' + d));
    throw new Error('one-word: ' + dup.length + ' phrase(s) under two keys in words.json — merge them, keeping the old key in `aliases`');
  }
  const hits = scan();
  const owed = hits.filter(h => OWED.includes(h.f)), bad = hits.filter(h => !OWED.includes(h.f));
  const per = {}; owed.forEach(h => (per[h.f] = (per[h.f] || 0) + 1));
  console.log('one-word: no phrase under two keys; ' + hits.length + ' literal(s) repeat words.json; owed by other lanes: ' + (Object.entries(per).map(([f, n]) => f + ' ' + n).join(', ') || 'none'));
  if (bad.length) {
    bad.forEach(h => console.log('  ' + h.rel + ':' + h.line + ' ' + JSON.stringify(h.s) + ' is text_(\'' + h.key + '\')'));
    throw new Error('one-word: ' + bad.length + ' literal(s) repeat a words.json value — read them through text_(key)');
  }
}
module.exports = { run, scan, twice };
if (require.main === module) run().catch(e => { console.error(e.message); process.exit(1); });
