#!/usr/bin/env node
/* @family. — tools/spec-tree.js THE TREE BY FORMULA (26 Nov, step 1 of "a country's spec goes in, the tree comes out MECHANICALLY"). From the
   readings of tools/spec-read.js (every source of data/settings/curriculum/<country>/sources/), for each country and subject:
     - <country>/headings.json, written (the documents' headings as printed; one-curriculum holds every `ref` to it);
     - THE GENERATED TREE (sources/tree-<subject>.json): a node per heading (a cross-document node where the same heading sits under the same
       parent: GCSE combined and separate, a year document's section every year), its name the heading as printed, its parent the heading
       above it, its levels on a leaf from the documents' level markers, its sources every heading it is (and a GCSE maths statement's code);
       ids by one rule: a node takes the id of the hand-built node it is the mutual best match of (most shared sources over all, ties A–Z),
       else <stem>x.<slugs of its path>;
     - docs/curriculum-diff-<country>.md: each hand-built node identical, renamed, merged (it joins several headings) or split (it is one of
       several on one heading), each heading no node has (missing), and question tagging and generated questions before and after;
     - THE SWITCH: the generated tree goes live (the hand file's nodes replaced) only if neither tagged questions nor generated questions fall
       (with every map of the hand file kept where its node keeps its id); otherwise the report says exactly why not;
     - docs/curriculum-gaps.md: every statement data/settings/curriculum/rules.json matches to no generator, per country, subject and level.
   Checks (rule 1.75): each stored text is the one its manifest hashes; the reader and the tree are the same bytes twice in one process and in
   a fresh one; every rule's skills are templates; every statement is matched or listed; `--prove` breaks each and fails unless caught. */
'use strict';
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const { ROOT, main, writeIfChanged } = require('./lib/gen.js');
const SR = require('./spec-read.js');

const RULES = 'data/settings/curriculum/rules.json';
const GAPS = 'docs/curriculum-gaps.md';
const ABOUT_H = 'THE GOVERNMENT DOCUMENTS\' OWN SECTION HEADINGS, exact, GENERATED by tools/spec-read.js from the stored sources (sources/*.tsv, the gov.uk PDFs\' text with its type; layouts in sources/layouts.json) — never edit by hand. Per subject, per document: `cite`, the content sections (a heading with statements under it), each of which some node\'s `src.ref` must cite; `groups`, the headings above them a broader node may cite; `skills`, the working-mathematically / working-scientifically strands, which are skills, not content, so no node need cite them. A year-by-year document\'s section is `Y<n> <heading>`; a group there is the heading itself, every year it appears. A GCSE science section is `<topic> – <sub-heading>`. GCSE maths statements (N1–S6) are the maths file\'s `statements`, not listed here. Checked by tools/one-curriculum.js: every `ref` is one of these, every `cite` heading is cited.';

const slug = s => String(s).toLowerCase().replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 32).replace(/-$/, '');
const key = (d, r) => d + '|' + r;

/* THE GENERATED NODES OF ONE SUBJECT: [{ key, name, parentKey, src: [{doc, ref}], levels }] in reading order. */
function nodesFrom(R, M, sub, levelOrder) {
  const out = [], by = {};
  Object.keys(M.docs).filter(k => M.docs[k].subject === sub).forEach(k => {
    const doc = M.docs[k].doc, r = R[sub][doc], kOf = {};
    r.headings.forEach(h => {
      if (h.kind === 'skill') return;
      const pk = h.parent ? kOf[h.parent] : '', k2 = (pk || '') + '/' + h.text.toLowerCase();
      kOf[h.ref] = k2;
      let n = by[k2];
      if (!n) { n = by[k2] = { key: k2, name: h.text, parentKey: pk || '', src: [], levels: [] }; out.push(n); }
      if (!n.src.some(s => s.doc === doc && s.ref === h.ref)) n.src.push({ doc, ref: h.ref });
      h.levels.forEach(l => { if (!n.levels.includes(l)) n.levels.push(l); });
      r.statements.filter(s => s.ref === h.ref && s.code).forEach(s => n.src.push({ doc, ref: s.code }));
    });
  });
  const kids = new Set(out.map(n => n.parentKey));
  out.forEach(n => { n.leaf = !kids.has(n.key); n.levels = levelOrder.filter(l => n.levels.includes(l)); });
  return out;
}

/* THE ID RULE: mutual best match by shared sources (Jaccard; ties by the lower id / earlier node), else <stem>x.<path slugs>. */
function stemOf(T) { const ids = T.nodes.map(n => n.id), p = ids[0].split('.'); let i = 0; while (i < p.length - 1 && ids.every(x => x.split('.')[i] === p[i])) i++; return p.slice(0, i).join('.') + '.'; }
function ids(G, T) {
  const srcH = T.nodes.map(h => new Set(h.src.map(s => key(s.doc, s.ref)))), srcG = G.map(g => new Set(g.src.map(s => key(s.doc, s.ref))));
  const jac = (a, b) => { let i = 0; a.forEach(x => { if (b.has(x)) i++; }); return i ? i / (a.size + b.size - i) : 0; };
  const J = G.map((g, gi) => T.nodes.map((h, hi) => jac(srcG[gi], srcH[hi])));
  const bestH = J.map(row => { let b = -1, v = 0; row.forEach((x, hi) => { if (x > v || (x === v && x > 0 && T.nodes[hi].id < T.nodes[b].id)) { v = x; b = hi; } }); return b; });
  const bestG = T.nodes.map((h, hi) => { let b = -1, v = 0; G.forEach((g, gi) => { const x = J[gi][hi]; if (x > v) { v = x; b = gi; } }); return b; });
  const stem = stemOf(T), byKey = {}, used = new Set();
  G.forEach((g, gi) => { const hi = bestH[gi]; if (hi >= 0 && bestG[hi] === gi) { g.id = T.nodes[hi].id; g.hand = T.nodes[hi]; used.add(g.id); } byKey[g.key] = g; });
  G.forEach(g => {
    if (g.id) return;
    const parts = []; for (let n = g; n; n = byKey[n.parentKey]) parts.unshift(slug(n.name));
    let id = stem + 'x.' + parts.join('.'), i = 2; while (used.has(id)) id = stem + 'x.' + parts.join('.') + '-' + i++;
    g.id = id; used.add(id);
  });
  G.forEach(g => { g.parent = g.parentKey ? byKey[g.parentKey].id : ''; });
  return { srcH, srcG };
}
const asNodes = G => G.map(g => { const n = { id: g.id, name: g.name, parent: g.parent }; if (g.leaf && g.levels.length) n.levels = g.levels; n.src = g.src; return n; });

/* THE DIFF: each hand node against the generated nodes it cites. */
function diff(G, T, S) {
  const gOf = {}; G.forEach((g, gi) => S.srcG[gi].forEach(k => { if (gOf[k] == null) gOf[k] = gi; }));
  const hOfG = G.map(() => []);
  const rows = T.nodes.map((h, hi) => { const gs = [...new Set([...S.srcH[hi]].map(k => gOf[k]).filter(x => x != null))]; gs.forEach(gi => hOfG[gi].push(hi)); return { h, gs }; });
  const low = s => s.toLowerCase();
  rows.forEach(r => {
    if (!r.gs.length) r.kind = 'missing';
    else if (r.gs.length > 1) r.kind = 'merged';
    else if (hOfG[r.gs[0]].length > 1) r.kind = 'split';
    else r.kind = low(G[r.gs[0]].name) === low(r.h.name) ? 'identical' : 'renamed';
  });
  const unheld = G.filter((g, gi) => !hOfG[gi].length);
  return { rows, unheld };
}

/* TAGGING AND GENERATED QUESTIONS for a set of country entries: questions with a node, per subject, and generated questions. */
function measure(E, rows0) {
  const CU = require('./lib/curriculum.js'), QG = require('./lib/qgen.js');
  const gen = QG.emit(undefined, E).rows.filter(r => r.kind === 'question');
  const rows = rows0.filter(r => !String(r.paper_id || '').startsWith(QG.SET_PREFIX)).map(r => Object.assign({}, r))
    .concat(QG.emit(undefined, E).rows.map(r => Object.assign({}, r)));
  const t = CU.assign(rows, E), out = {};
  Object.keys(CU.SUBJECTS).forEach(k => {
    if (!t[k]) return;
    const pre = E.filter(e => e.subject === k).map(e => QG.cfg(e).row_prefix);
    out[k] = { questions: t[k].questions, tagged: t[k].tagged, generated: gen.filter(r => CU.ofSubject(E, k).some(e => e.T.nodes.some(n => n.id === r[CU.FIELD]))).length };
    out[k].nodes = new Set(rows.filter(r => r[CU.FIELD]).map(r => r[CU.FIELD])).size;
    void pre;
  });
  return out;
}

/* A CANDIDATE COUNTRY FILE: the hand file with the generated nodes, every map kept only where its node keeps its id. */
function candidate(T, nodes) {
  const ids = new Set(nodes.map(n => n.id)), C = JSON.parse(JSON.stringify(T));
  C.nodes = nodes;
  ['ideas', 'set', 'topic', 'spec', 'gen_ideas'].forEach(m => { if (!C[m]) return; Object.keys(C[m]).forEach(k => { const v = m === 'gen_ideas' ? k : C[m][k]; if (!ids.has(v)) delete C[m][k]; }); });
  if (C.templates) Object.keys(C.templates).forEach(k => { if (!ids.has(k)) delete C.templates[k]; });
  return C;
}

/* STATEMENTS AGAINST THE RULE TABLE. */
function rulesOf() { return JSON.parse(fs.readFileSync(path.join(ROOT, RULES), 'utf8')); }
function match(R, RU) {
  const res = [];
  Object.keys(R).forEach(sub => Object.keys(R[sub]).forEach(doc => R[sub][doc].statements.forEach(s => {
    const skills = [];
    RU.rules.filter(r => r.subject === sub).forEach(r => {
      const hit = r.any.some(p => new RegExp(p, 'i').test(s.text)) && !(r.none || []).some(p => new RegExp(p, 'i').test(s.text));
      if (hit) r.skills.forEach(k => { if (!skills.includes(k)) skills.push(k); });
    });
    res.push({ sub, doc, s, skills });
  })));
  return res;
}
function gapsMd(all) {
  const L = ['# Statements with no generator yet', '', 'GENERATED by tools/spec-tree.js from the stored government documents (tools/spec-read.js) and the rule table data/settings/curriculum/rules.json — never edit by hand. A statement any rule matches is taught by that rule\'s qgen skills; the rest are listed here, per country, subject and level (a statement taught at several levels is counted at each).', ''];
  const sum = ['| Country | Subject | Level | Statements | Matched | No generator yet |', '|---|---|---|---|---|---|'], body = [];
  all.forEach(({ country, list, levels }) => {
    Object.keys(levels).forEach(sub => levels[sub].forEach(lv => {
      const at = list.filter(x => x.sub === sub && x.s.levels.includes(lv));
      if (!at.length) return;
      const gap = at.filter(x => !x.skills.length);
      sum.push('| ' + country + ' | ' + sub + ' | ' + lv + ' | ' + at.length + ' | ' + (at.length - gap.length) + ' | ' + gap.length + ' |');
      body.push('', '## ' + country + ' — ' + sub + ' — ' + lv + ' (' + gap.length + ' of ' + at.length + ')', '');
      gap.forEach(x => body.push('- `' + x.doc + '` ' + x.s.ref + (x.s.code ? ' ' + x.s.code : '') + ': ' + x.s.text.replace(/\|/g, '/')));
    }));
  });
  return L.concat(sum, body).join('\n') + '\n';
}

function diffMd(country, per, decided) {
  const L = ['# The ' + country.toUpperCase() + ' curriculum trees: hand-built against generated', '', 'GENERATED by tools/spec-tree.js — never edit by hand. The generated tree is the documents\' headings by formula (tools/spec-read.js on data/settings/curriculum/' + country + '/sources/); each hand-built node is compared with the generated nodes its sources cite: **identical** (one heading, same name), **renamed** (one heading, its own name), **merged** (it joins several headings), **split** (it is one of several nodes on one heading), **missing** (it cites no heading). A heading no hand-built node cites is listed as missing from the hand tree.', ''];
  Object.keys(per).forEach(sub => {
    const p = per[sub], c = {}; p.diff.rows.forEach(r => { c[r.kind] = (c[r.kind] || 0) + 1; });
    L.push('## ' + sub, '', '| | Count |', '|---|---|', '| Hand-built nodes | ' + p.hand + ' |', '| Generated nodes | ' + p.gen.length + ' (ids kept from the hand tree: ' + p.gen.filter(g => g.hand).length + ') |');
    ['identical', 'renamed', 'merged', 'split', 'missing'].forEach(k => L.push('| ' + k + ' | ' + (c[k] || 0) + ' |'));
    L.push('| headings no hand node cites | ' + p.diff.unheld.length + ' |', '');
    L.push('Question tagging and generated questions (tools/lib/curriculum.js assign and tools/lib/qgen.js emit on the live files, then with this subject\'s nodes replaced by the generated ones and every map kept where its node keeps its id):', '',
      '| | Before (hand) | After (generated) |', '|---|---|---|',
      '| ' + sub + ' questions tagged | ' + p.before.tagged + ' of ' + p.before.questions + ' | ' + p.after.tagged + ' of ' + p.after.questions + ' |',
      '| distinct nodes tagged | ' + p.before.nodes + ' | ' + p.after.nodes + ' |',
      '| generated questions | ' + p.before.generated + ' | ' + p.after.generated + ' |', '');
    ['renamed', 'merged', 'split', 'missing'].forEach(k => {
      const rs = p.diff.rows.filter(r => r.kind === k); if (!rs.length) return;
      L.push('### ' + k + ' (' + rs.length + ')', '');
      rs.forEach(r => L.push('- `' + r.h.id + '` ' + r.h.name + (r.gs.length ? ' → ' + r.gs.map(gi => '"' + p.gen[gi].name + '"').join(', ') : '')));
      L.push('');
    });
    if (p.diff.unheld.length) { L.push('### headings no hand node cites (' + p.diff.unheld.length + ')', ''); p.diff.unheld.forEach(g => L.push('- `' + g.id + '` ' + g.name + ' (' + g.src.map(s => s.doc + ': ' + s.ref).join('; ') + ')')); L.push(''); }
  });
  L.push('## The switch', '', decided.switched ? 'SWITCHED: neither tagged questions nor generated questions fell, so the generated nodes are the live tree.' : 'NOT SWITCHED — the hand-built trees stay live: ' + decided.why.join('; ') + '.', '');
  return L.join('\n') + '\n';
}

/* EVERYTHING FOR EVERY COUNTRY, as text: { files: {path: text}, report }. Pure: the same sources give the same bytes. */
function build(opt) {
  opt = opt || {};
  const CU = require('./lib/curriculum.js'), SD = require('./lib/site-data.js');
  const files = {}, gapsAll = [], decisions = {};
  const E = CU.entries(), rows = opt.rows || SD.json('data/questions.json'), RU = opt.rules || rulesOf();
  SR.countries().forEach(country => {
    const M = SR.manifest(country), LY = SR.layouts(country), R = SR.readAll(country, opt.read);
    files[path.join(SR.DIR, country, 'headings.json')] = JSON.stringify(SR.headingsFile(country, R, ABOUT_H), null, 1) + '\n';
    const per = {}, why = [];
    let E2 = E.slice();
    Object.keys(R).forEach(sub => {
      const e = E.find(x => x.country === country && x.subject === sub);
      const G = nodesFrom(R, M, sub, LY.levels[sub]);
      if (!e) { G.forEach(g => { g.id = country + '.' + sub.slice(0, 2) + '.x.' + slug(g.key); }); return; }
      const SX = ids(G, e.T), nodes = asNodes(G);
      files[path.join(SR.DIR, country, SR.SRC, 'tree-' + sub + '.json')] = JSON.stringify({ about: 'GENERATED by tools/spec-tree.js from the stored sources — never edit by hand. The ' + sub + ' tree by formula: a node per heading of the documents, named as printed; see docs/curriculum-diff-' + country + '.md.', nodes }, null, 1) + '\n';
      per[sub] = { e, gen: G, nodes, hand: e.T.nodes.length, diff: diff(G, e.T, SX) };
      const C = candidate(e.T, nodes);
      E2 = E2.map(x => x === e ? Object.assign(Object.create(Object.getPrototypeOf(x)), x, { T: C }) : x);
      per[sub].C = C;
    });
    if (!opt.skipMeasure) {
      const before = measure(E, rows), after = measure(E2, rows);
      Object.keys(per).forEach(sub => {
        per[sub].before = before[sub]; per[sub].after = after[sub];
        if (after[sub].tagged < before[sub].tagged) why.push(sub + ': tagged questions would fall from ' + before[sub].tagged + ' to ' + after[sub].tagged);
        if (after[sub].generated < before[sub].generated) why.push(sub + ': generated questions would fall from ' + before[sub].generated + ' to ' + after[sub].generated);
      });
      const switched = !why.length;
      decisions[country] = { switched, why };
      files['docs/curriculum-diff-' + country + '.md'] = diffMd(country, per, decisions[country]);
    }
    gapsAll.push({ country, list: match(R, RU), levels: LY.levels, R });
    decisions[country] = decisions[country] || { switched: false, why: [] };
    decisions[country].per = per;
  });
  files[GAPS] = gapsMd(gapsAll);
  return { files, gapsAll, decisions };
}
const hashOf = files => require('crypto').createHash('sha256').update(Object.keys(files).sort().map(k => k + '\n' + files[k]).join('\n')).digest('hex');

/* THE CHECKS (each returns problems). */
function problems(opt) {
  opt = opt || {};
  const bad = [];
  SR.countries().forEach(country => {
    const M = opt.manifest || SR.manifest(country);
    Object.keys(M.docs).forEach(k => {
      const d = M.docs[k], t = opt.text && opt.text[k] != null ? opt.text[k] : SR.sourceText(country, d.file);
      if (SR.sha(t) !== d.text_sha256) bad.push(country + ' ' + k + ': the stored text is not the one the manifest hashes (refresh with node tools/spec-read.js --fetch ' + country + ')');
      if (!/^https:\/\/assets\.publishing\.service\.gov\.uk\//.test(d.pdf || '') || !/^[0-9a-f]{64}$/.test(d.sha256 || '') || !d.fetched) bad.push(country + ' ' + k + ': no gov.uk address, sha256 or date in the manifest');
    });
  });
  const T = require('./lib/qgen.js').table(), RU = opt.rules || rulesOf();
  RU.rules.forEach((r, i) => r.skills.forEach(s => { if (!T.templates.some(t => t.id === s)) bad.push(RULES + ' rule ' + (i + 1) + ': skill ' + s + ' is no template of data/settings/qgen.json'); }));
  const b = opt.built || build({ rules: RU, skipMeasure: true, read: opt.read });
  const listed = opt.gapsText != null ? opt.gapsText : b.files[GAPS];
  b.gapsAll.forEach(({ country, list }) => list.forEach(x => {
    if (x.skills.length) return;
    const line = '- `' + x.doc + '` ' + x.s.ref + (x.s.code ? ' ' + x.s.code : '') + ': ' + x.s.text.replace(/\|/g, '/');
    if (!x.s.levels.length) bad.push(country + ' ' + x.sub + ' ' + x.doc + ': a statement with no level: ' + x.s.text.slice(0, 60));
    else if (!listed.includes(line)) bad.push(country + ' ' + x.sub + ' ' + x.doc + ': a statement neither matched nor listed in ' + GAPS + ': ' + x.s.text.slice(0, 60));
  }));
  /* DETERMINISM: twice here, then in a fresh process. */
  const h1 = hashOf(b.files), h2 = hashOf((opt.again || (() => build({ rules: RU, skipMeasure: true, read: opt.read })))().files);
  if (h1 !== h2) bad.push('the reader gave different bytes twice from the same sources');
  if (!opt.noFresh) {
    const h3 = cp.execFileSync(process.execPath, [__filename, '--hash'], { cwd: ROOT, encoding: 'utf8' }).trim();
    if (h3 !== h1) bad.push('a fresh process read different bytes from the same sources');
  }
  return bad;
}

/* --prove: each break must be caught. */
function prove() {
  const country = 'uk', M = SR.manifest(country), k0 = Object.keys(M.docs)[0], RU = rulesOf();
  let flip = 0;
  const BREAKS = [
    { name: 'a stored text edited', o: () => ({ text: { [k0]: SR.sourceText(country, M.docs[k0].file).replace('\t0\t', '\t1\t') } }) },
    { name: 'a manifest hash wrong', o: () => { const m = JSON.parse(JSON.stringify(M)); m.docs[k0].text_sha256 = '0'.repeat(64); return { manifest: m }; } },
    { name: 'a rule naming no template', o: () => { const r = JSON.parse(JSON.stringify(RU)); r.rules[0].skills.push('no-such-skill'); return { rules: r }; } },
    { name: 'a gap not listed', o: () => { const b = build({ rules: RU, skipMeasure: true }); const g = b.files[GAPS].split('\n'); const i = g.findIndex(l => /^- `/.test(l)); g.splice(i, 1); return { built: b, gapsText: g.join('\n') }; } },
    { name: 'a reader that is not deterministic', o: () => ({ again: () => { const b = build({ rules: RU, skipMeasure: true }); flip++; b.files['x'] = String(flip); return b; } }) },
  ];
  const missed = [];
  BREAKS.forEach(B => { const o = Object.assign({ noFresh: true }, B.o()); if (!problems(o).length) missed.push(B.name); });
  if (missed.length) throw new Error('spec-tree --prove: missed ' + missed.join(', '));
  return BREAKS.length;
}

function run() {
  const t = build();
  Object.keys(t.files).forEach(f => writeIfChanged(path.join(ROOT, f), t.files[f]));
  const CU = require('./lib/curriculum.js');
  Object.keys(t.decisions).forEach(country => {
    const d = t.decisions[country];
    if (d.switched) Object.keys(d.per).forEach(sub => { const p = d.per[sub]; writeIfChanged(path.join(ROOT, p.e.file), JSON.stringify(p.C, null, 1) + '\n'); });
    void CU;
  });
  const bad = problems({ built: build({ skipMeasure: true }) });
  const n = prove();
  const lines = [];
  Object.keys(t.decisions).forEach(country => {
    const d = t.decisions[country];
    Object.keys(d.per).forEach(sub => {
      const p = d.per[sub], c = {}; p.diff.rows.forEach(r => { c[r.kind] = (c[r.kind] || 0) + 1; });
      lines.push(country + ' ' + sub + ': ' + p.gen.length + ' generated nodes (' + p.gen.filter(g => g.hand).length + ' ids kept) for ' + p.hand + ' hand-built: '
        + ['identical', 'renamed', 'merged', 'split', 'missing'].map(k => (c[k] || 0) + ' ' + k).join(', ') + '; tagged ' + p.before.tagged + ' -> ' + p.after.tagged + ', generated ' + p.before.generated + ' -> ' + p.after.generated);
    });
    lines.push(country + ': ' + (d.switched ? 'SWITCHED to the generated tree' : 'not switched (' + d.why.join('; ') + ')'));
  });
  const g = t.gapsAll.map(x => x.country + ' ' + x.list.length + ' statements, ' + x.list.filter(y => !y.skills.length).length + ' with no generator yet').join('; ');
  console.log('spec-tree: ' + lines.join(' | ') + ' | ' + g + ' | determinism, sources and rules checked, --prove ' + n + ' breaks caught');
  if (bad.length) throw new Error('spec-tree: ' + bad.length + ' problem(s):\n  ' + bad.slice(0, 20).join('\n  '));
}

module.exports = { run, build, problems, prove, nodesFrom, match };
main(module, () => {
  if (process.argv.includes('--hash')) { console.log(hashOf(build({ skipMeasure: true }).files)); return; }
  if (process.argv.includes('--prove')) { console.log('spec-tree --prove: every break caught (' + prove() + ')'); return; }
  return run();
});
