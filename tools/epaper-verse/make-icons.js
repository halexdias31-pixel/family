/* make-icons.js - one site icon (TILE_ICONS) per verse into icons.h, and every icon of data/icons.json into pictures.h (470); never edit either by hand. */
// node tools/epaper-verse/make-icons.js [--preview DIR] [--days 0,2,9]   (--preview: PNGs of what the panel shows)
'use strict';
const fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const DIR = __dirname, ROOT = path.join(DIR, '..', '..');
const SIZES = [96, 64, 40, 20];   // the firmware takes the biggest that leaves the verse room; 20 sits beside the reference

const tiles = fs.readFileSync(path.join(ROOT, 'js', 'tiles.js'), 'utf8');
const ICONS = new Function(tiles.slice(0, tiles.indexOf('\n};', tiles.indexOf('const TILE_ICONS')) + 3) + ';return TILE_ICONS')();
const VERSES = [...fs.readFileSync(path.join(DIR, 'verse.cpp'), 'utf8').matchAll(/^\s*\{ "(.*)", "(.*)" \},$/gm)].map(m => [m[1], m[2]]);

/* By meaning: the first rule whose words the verse holds wins. The set has no heart or sheep, so love is the
   spark and the shepherd is a person. */
const RULES = [
  ['join', /\b(shepherd)\b/i],
  ['spot', /\b(light|lamp|shine|shineth|darkness|sun)\b/i],
  ['book', /\b(word|scripture|law)\b/i],
  ['unlock', /\b(truth|free)\b/i],
  ['in', /\b(the way|come unto me|rest)\b/i],
  ['figure', /\b(hills|earth|heaven|created|mountains?)\b/i],
  ['lock', /\b(refuge|fortress|tower|safe|shield|stronghold|keep)\b/i],
  ['chat', /\b(pray|prayer|ask|knock|answer|speak)\b/i],
  ['search', /\b(seek|find|look)\b/i],
  ['show', /\b(sight|see|eyes|faith)\b/i],
  ['share', /\b(cast|burden|care|anxious|thought for)\b/i],
  ['sync', /\b(morning|yesterday|for ever|new every|same)\b/i],
  ['again', /\b(season|time|day|tomorrow)\b/i],
  ['flag', /\b(strong|strength|courage|overcome|victory|wings|weary|faint)\b/i],
  ['join', /\b(neighbour|one another|brother|others|men|child|peacemakers)\b/i],
  ['sound', /\b(rejoice|sing|singing|merry|joy)\b/i],
  ['plus', /\b(give|giveth|added|supply|gift|all things)\b/i],
  ['tick', /\b(good|right|justly|mercy)\b/i],
  ['spark', /./],
];
const pick = text => RULES.find(([, re]) => re.test(text))[0];
const MAP = VERSES.map(([t]) => pick(t));
const USED = [...new Set(MAP)];

function svg(name, px) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 18 17" fill="none" stroke="#000"
    stroke-width="${px <= 20 ? 1.8 : 1.5}" stroke-linecap="round" stroke-linejoin="round">${ICONS[name]}</svg>`;
}

/* A 1-bit greyscale PNG of rows (1 = black): re-reading it is exact, so once made it is the icon's source (483). */
function png1_(rows) {
  const zlib = require('zlib'), h = rows.length, w = rows[0].length, stride = 1 + Math.ceil(w / 8), raw = Buffer.alloc(h * stride);
  rows.forEach((r, y) => r.forEach((p, x) => { if (!p) raw[y * stride + 1 + (x >> 3)] |= 0x80 >> (x & 7); }));
  const crc = b => { let c = ~0; for (const v of b) { c ^= v; for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xEDB88320 & -(c & 1)); } return ~c >>> 0; };
  const chunk = (t, d) => { const l = Buffer.alloc(4), c = Buffer.alloc(4), td = Buffer.concat([Buffer.from(t, 'latin1'), d]); l.writeUInt32BE(d.length); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
  const ih = Buffer.alloc(13); ih.writeUInt32BE(w, 0); ih.writeUInt32BE(h, 4); ih[8] = 1; ih[9] = 0;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ih), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}

(async () => {
  const a = process.argv, pv = a.indexOf('--preview'), dv = a.indexOf('--days');
  const exe = ['/opt/pw-browsers/chromium-1194/chrome-linux/chrome', '/opt/pw-browsers/chromium/chrome-linux/chrome'].find(p => fs.existsSync(p));
  const browser = await chromium.launch(exe ? { executablePath: exe } : {});
  const page = await browser.newPage();
  await page.setContent('<canvas id="c"></canvas>');
  const bits = {};   // name -> size -> rows of 0/1
  for (const name of USED) for (const px of SIZES) {
    (bits[name] = bits[name] || {})[px] = await page.evaluate(async ([src, px]) => {
      const img = new Image(); img.src = 'data:image/svg+xml,' + encodeURIComponent(src); await img.decode();
      const c = document.getElementById('c'); c.width = c.height = px;
      const g = c.getContext('2d'); g.clearRect(0, 0, px, px); g.drawImage(img, 0, 0, px, px);
      const d = g.getImageData(0, 0, px, px).data, rows = [];
      for (let y = 0; y < px; y++) { const r = []; for (let x = 0; x < px; x++) r.push(d[(y * px + x) * 4 + 3] > 110 ? 1 : 0); rows.push(r); }
      return rows;
    }, [svg(name, px), px]);
  }

  const out = ['// icons.h - GENERATED by make-icons.js from the site\'s TILE_ICONS (js/tiles.js). Do not edit; re-run the script.',
    '// Adafruit GFX drawBitmap format: rows MSB first, each row padded to a byte, 1 = black.', '#pragma once', '#include <pgmspace.h>', '',
    `const int ICON_SIZES[${SIZES.length}] = { ${SIZES.join(', ')} };`, ''];
  for (const name of USED) for (const px of SIZES) {
    const bytes = [];
    for (const r of bits[name][px]) for (let x = 0; x < px; x += 8) { let b = 0; for (let k = 0; k < 8; k++) b = (b << 1) | (r[x + k] || 0); bytes.push('0x' + b.toString(16).padStart(2, '0')); }
    out.push(`const uint8_t ICON_${name}_${px}[] PROGMEM = {`);
    const lines = []; for (let i = 0; i < bytes.length; i += 24) lines.push('  ' + bytes.slice(i, i + 24).join(','));
    out.push(lines.join(',\n')); out.push('};');
  }
  out.push('', '// One row per icon, one column per size in ICON_SIZES.', `const uint8_t *const ICONS[${USED.length}][${SIZES.length}] = {`);
  USED.forEach(n => out.push(`  { ${SIZES.map(px => `ICON_${n}_${px}`).join(', ')} },  // ${n}`));
  out.push('};', '', `// Which icon each verse draws, in VERSES order (${VERSES.length}).`, `const uint8_t VERSE_ICON[${VERSES.length}] = {`);
  for (let i = 0; i < MAP.length; i += 20) out.push('  ' + MAP.slice(i, i + 20).map(n => USED.indexOf(n)).join(', ') + ',');
  out.push('};', '');
  fs.writeFileSync(path.join(DIR, 'icons.h'), out.join('\n'));
  /* AND THE ICONS THEMSELVES (470, 479): every row of data/icons.json at 120x160 in 1 bit, for the screen's Icon mode. */
  const PICS = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'icons.json'), 'utf8'));
  const pout = ['// pictures.h - GENERATED by make-icons.js from data/icons.json (each row\'s 1-bit PNG, data/icons/120/<id>.png). Do not edit; re-run the script.',
    '// Adafruit GFX drawBitmap format, 120x160, rows MSB first, 1 = black.', '#pragma once', '#include <pgmspace.h>', '',
    'const int PIC_W = 120, PIC_H = 160;', `const int NPICS = ${PICS.length};`, ''];
  const SMALL = path.join(ROOT, 'data', 'icons', '120'); fs.mkdirSync(SMALL, { recursive: true });
  for (const [k, row] of PICS.entries()) {
    /* The real icon (479): its 1-bit PNG fitted to 120x160, grey again by the scaling, dithered back to 1 bit; every icon has one (483). */
    /* THE MASTER FIRST (499): data/icons/master/<id>.jpg, greyscale at 600px from Commons, kept so a better reduction can always be made again. */
    const master = path.join(ROOT, 'data', 'icons', 'master', row.id + '.jpg');
    const big = path.join(ROOT, 'data', 'icons', row.id + '.png'), file = path.join(SMALL, row.id + '.png');
    if (!row.image) throw new Error(row.id + ' has no real image — an icon without one is left out of data/icons.json (483)');
    const from = fs.existsSync(master) ? master : fs.existsSync(big) ? big : file;
    const src = 'data:image/' + (from === master ? 'jpeg' : 'png') + ';base64,' + fs.readFileSync(from).toString('base64');
    const rows = await page.evaluate(async ([src, photo, stretch]) => {
      const img = new Image(); img.src = src; await img.decode();
      const c = document.getElementById('c'); c.width = 120; c.height = 160;
      const g = c.getContext('2d'); g.fillStyle = '#fff'; g.fillRect(0, 0, 120, 160);
      const f = photo ? Math.min(120 / img.width, 160 / img.height) : 1, w = photo ? Math.round(img.width * f) : 120, h = photo ? Math.round(img.height * f) : 160;
      g.imageSmoothingQuality = 'high'; g.drawImage(img, (120 - w) >> 1, (160 - h) >> 1, w, h);
      const d = g.getImageData(0, 0, 120, 160).data, v = new Float32Array(120 * 160), out = [];
      for (let i = 0; i < v.length; i++) v[i] = d[i * 4];
      /* A GREY MASTER IS STRETCHED to its own 2nd-98th percentile first (499), inside the picture only, or a dim scan dithers to grey mush. */
      if (stretch) {
        const x0 = (120 - w) >> 1, y0 = (160 - h) >> 1, inside = [];
        for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) inside.push(v[y * 120 + x]);
        inside.sort((a, b) => a - b);
        const lo = inside[Math.floor(inside.length * 0.02)] || 0, hi = inside[Math.floor(inside.length * 0.98)] || 255;
        if (hi - lo > 16) for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) {
          const i = y * 120 + x; v[i] = Math.max(0, Math.min(255, (v[i] - lo) * 255 / (hi - lo)));
        }
      }
      for (let y = 0; y < 160; y++) { const r = []; for (let x = 0; x < 120; x++) {
        const i = y * 120 + x, on = v[i] < 128 ? 1 : 0, e = photo ? v[i] - (on ? 0 : 255) : 0; r.push(on);
        if (e) { if (x < 119) v[i + 1] += e * 7 / 16; if (y < 159) { if (x) v[i + 119] += e * 3 / 16; v[i + 120] += e * 5 / 16; if (x < 119) v[i + 121] += e / 16; } }
      } out.push(r); }
      return out;
    }, [src, true, from === master]);
    fs.writeFileSync(file, png1_(rows));   // the widget draws this very bitmap, so widget == screen (483)
    const bytes = [];
    for (const r of rows) for (let x = 0; x < 120; x += 8) { let b = 0; for (let j = 0; j < 8; j++) b = (b << 1) | (r[x + j] || 0); bytes.push('0x' + b.toString(16).padStart(2, '0')); }
    pout.push(`const uint8_t PIC_${k}[] PROGMEM = {  // ${row.id}`);
    const ls = []; for (let i = 0; i < bytes.length; i += 30) ls.push('  ' + bytes.slice(i, i + 30).join(','));
    pout.push(ls.join(',\n'), '};');
  }
  pout.push('', `const uint8_t *const PICS[${PICS.length}] = { ${PICS.map((_, k) => 'PIC_' + k).join(', ')} };`,
    `const char *const PIC_TITLES[${PICS.length}] = {`, ...PICS.map(r => '  ' + JSON.stringify(r.title) + ','), '};', '');
  fs.writeFileSync(path.join(DIR, 'pictures.h'), pout.join('\n'));
  console.log(`pictures.h: ${PICS.length} icons`);
  console.log(`icons.h: ${VERSES.length} verses, ${USED.length} icons (${USED.map(n => n + ' ' + MAP.filter(m => m === n).length).join(', ')})`);

  if (pv > 0) {   // what the panel shows, laid out as verse.cpp lays it out (fonts are Chromium's serif, near FreeSerif)
    const dir = a[pv + 1]; fs.mkdirSync(dir, { recursive: true });
    const days = dv > 0 ? a[dv + 1].split(',').map(Number) : [0, 2, 9, 43, 78];
    for (const i of days) {
      const html = await page.evaluate(([v, ref, b, sizes]) => {
        const c = document.getElementById('c'); c.width = c.height = 200; const g = c.getContext('2d');
        const M = 8, W = 184, REF_TOP = 176, fonts = [['17px serif', 24], ['13px serif', 18]];
        const wrap = () => { const L = []; let line = ''; for (const w of v.split(' ')) { const t = line ? line + ' ' + w : w; if (g.measureText(t).width <= W || !line) line = t; else { L.push(line); line = w; } } if (line) L.push(line); return L; };
        let lay = null;
        for (const si of [0, 1, 2]) { for (const f of fonts) { g.font = f[0]; const L = wrap(); if (sizes[si] + 6 + L.length * f[1] <= REF_TOP - M) { lay = { px: sizes[si], f, L }; break; } } if (lay) break; }
        if (!lay) { g.font = fonts[1][0]; lay = { px: 20, f: fonts[1], L: wrap(), beside: 1 }; }
        g.fillStyle = '#fff'; g.fillRect(0, 0, 200, 200); g.fillStyle = '#000';
        const blk = (lay.beside ? 0 : lay.px + 6) + lay.L.length * lay.f[1];
        let top = M + Math.max(0, (REF_TOP - M - blk) >> 1);
        const dot = (rows, x0, y0) => rows.forEach((r, y) => r.forEach((p, x) => p && g.fillRect(x0 + x, y0 + y, 1, 1)));
        if (!lay.beside) { dot(b[lay.px], 100 - lay.px / 2, top); top += lay.px + 6; }
        g.font = lay.f[0]; g.textBaseline = 'alphabetic';
        lay.L.forEach((l, k) => g.fillText(l, M + (W - g.measureText(l).width) / 2, top + (k + 1) * lay.f[1] - 6));
        g.fillRect(70, REF_TOP, 60, 1); g.font = 'italic 13px serif';
        const rw = g.measureText(ref).width, iw = lay.beside ? 24 : 0, x = M + (W - rw - iw) / 2;
        if (lay.beside) dot(b[20], x, 179);
        g.fillText(ref, x + iw, 194);
        const d = g.getImageData(0, 0, 200, 200);   // to 1 bit, as the panel has it
        for (let k = 0; k < d.data.length; k += 4) { const on = d.data[k] < 128 ? 0 : 255; d.data[k] = d.data[k + 1] = d.data[k + 2] = on; }
        g.putImageData(d, 0, 0); return c.toDataURL();
      }, [VERSES[i][0], VERSES[i][1], bits[MAP[i]], SIZES]);
      const f = path.join(dir, `day-${String(i + 1).padStart(2, '0')}-${MAP[i]}.png`);
      fs.writeFileSync(f, Buffer.from(html.split(',')[1], 'base64')); console.log(f);
    }
  }
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
