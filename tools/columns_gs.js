#!/usr/bin/env node
/* WRITES the generated block of backend/constants.gs from data/settings/columns.json and js/layout.js's LAYOUT_COL (730), so layoutClean_ knows the columns the site does.
   Apps Script cannot read the repo, so the list is copied; check-doors fails when the copy is stale. `--check` only compares. */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
function columnsGs() {
  const rows = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'settings', 'columns.json'), 'utf8'));
  const on = v => String(v).toUpperCase() === 'TRUE';
  const screens = rows.filter(r => r && r.screen).map(r => String(r.screen));
  const cards = rows.filter(r => r && r.screen && on(r.cards)).map(r => String(r.screen));
  const lay = fs.readFileSync(path.join(ROOT, 'js', 'layout.js'), 'utf8');
  const m = /const LAYOUT_COL = \{([^}]*)\}/.exec(lay);
  const widgets = m ? [...m[1].matchAll(/:\s*'([a-z]+)'/g)].map(x => x[1]) : [];
  const q = a => '[' + a.map(x => "'" + x + "'").join(', ') + ']';
  return '/* GENERATED by tools/columns_gs.js from data/settings/columns.json and LAYOUT_COL (730): re-run it, never edit by hand. */\n'
    + '/* Every column, the card columns (a card or widget may stand on them) and the widget columns, for layoutClean_ (core.gs). */\n'
    + 'const LAYOUT_SCREENS = ' + q(screens) + ';\n'
    + 'const LAYOUT_CARD_COLS = ' + q(cards) + ';\n'
    + 'const LAYOUT_WIDGET_COLS = ' + q(widgets) + ';\n';
}
const BEGIN = '/* ---------- COLUMNS (generated) ---------- */\n', END = '/* ---------- END COLUMNS ---------- */\n';
/* THE FILE WITH ITS BLOCK AS IT SHOULD BE: replaced where it is, else appended. */
function columnsInto(src) {
  const block = BEGIN + columnsGs() + END, a = src.indexOf(BEGIN), b = src.indexOf(END);
  return a !== -1 && b > a ? src.slice(0, a) + block + src.slice(b + END.length) : src.replace(/\n*$/, '\n\n') + block;
}
module.exports = { columnsGs, columnsInto };
if (require.main === module) {
  const file = path.join(ROOT, 'backend', 'constants.gs'), src = fs.readFileSync(file, 'utf8');
  const out = columnsInto(src);
  if (process.argv.includes('--check')) { console.log(out === src ? 'current' : 'STALE — run node tools/columns_gs.js'); process.exit(out === src ? 0 : 1); }
  fs.writeFileSync(file, out);
  console.log('wrote the columns block of backend/constants.gs');
}
