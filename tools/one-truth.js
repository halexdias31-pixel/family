#!/usr/bin/env node
/* @family. — tools/one-truth.js: EVERY TRUTH IN ONE PLACE (owner, 12 Nov; docs/history/1211). Three ratios for health.js: facts, file lists, id labels. */
'use strict';
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const ROOT = path.join(__dirname, '..');
const read = f => { try { return fs.readFileSync(path.join(ROOT, f), 'utf8'); } catch (e) { return ''; } };
const lineOf = (s, i) => s.slice(0, i).split('\n').length;
const ls = pats => execFileSync('git', ['ls-files', ...pats], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean);

/* WHERE A TRUTH CAN LIVE: the app, the backend, the tools, the checks and the settings files. */
const CODE = () => ls(['js/*.js', 'backend/*.gs', 'tools/*.js', 'check/*.js', 'check/**/*.js', 'index.html', 'sw.js', 'sync.js']);
const SETTINGS = () => ls(['data/settings/*.json']);

/* A GENERATED COPY IS NOT A SECOND TRUTH: a file headed WRITTEN/GENERATED BY tools/…, a "(generated)" … END block, or a line tools/tiers.js rewrites. */
function generatedSpans(f, src) {
  if (/(?:WRITTEN|GENERATED) BY tools\//i.test(src.split('\n').slice(0, 3).join('\n'))) return [[0, src.length]];
  const spans = [];
  for (const m of src.matchAll(/\(generated\)[^\n]*\n[\s\S]*?\bEND\b[^\n]*/g)) spans.push([m.index, m.index + m[0].length]);
  GEN_LINES().forEach(re => { for (const m of src.matchAll(new RegExp(re.source, 'g'))) spans.push([m.index, m.index + m[0].length]); });
  return spans;
}
/* The lines tools/tiers.js rewrites, read off its own `want` table so this never keeps a copy of it. */
let GEN_CACHE = null;
function GEN_LINES() {
  if (GEN_CACHE) return GEN_CACHE;
  const t = read('tools/tiers.js');
  GEN_CACHE = [...t.matchAll(/\[\/((?:const|window\\\.)[^/]*?) = [^,]*?\/,/g)].map(m => new RegExp(m[1].replace(/\\\./g, '\\.') + ' = [\\[{][^\\]}]*[\\]}];'));
  return GEN_CACHE;
}
const inSpans = (spans, i) => spans.some(([a, b]) => i >= a && i < b);

/* A FACT: a literal list of three or more values, or an object of three or more plain settings, with at least one word in it (not [0, 0, 0]). */
const LIT = String.raw`(?:'[^'\n]*'|"[^"\n]*"|-?\d+(?:\.\d+)?|true|false)`;
const ARR = new RegExp(String.raw`\[\s*((?:${LIT}\s*,\s*){2,}${LIT})\s*,?\s*\]`, 'g');
const OBJ = new RegExp(String.raw`\{\s*((?:[\w$]+|'[^'\n]*'|"[^"\n]*")\s*:\s*${LIT}\s*(?:,\s*(?:[\w$]+|'[^'\n]*'|"[^"\n]*")\s*:\s*${LIT}\s*){2,}),?\s*\}`, 'g');
const unq = s => s.trim().replace(/^['"]|['"]$/g, '');
const worded = vs => vs.some(v => /[a-z]{2,}/i.test(v));
function factsIn(f, src) {
  const out = [], spans = generatedSpans(f, src);
  const add = (key, i, show) => { if (!inSpans(spans, i)) out.push({ key, at: f + ':' + lineOf(src, i), show }); };
  if (f.endsWith('.json')) {
    let j; try { j = JSON.parse(src); } catch (e) { return out; }
    const walk = v => {
      if (Array.isArray(v)) { const p = v.filter(x => x === null || typeof x !== 'object'); if (p.length === v.length && v.length >= 3 && worded(v.map(String))) add('A' + v.map(String).join('\u0001'), Math.max(0, src.indexOf(JSON.stringify(v[0]))), JSON.stringify(v).slice(0, 80)); else v.forEach(walk); return; }
      if (v && typeof v === 'object') { const ks = Object.keys(v).filter(k => v[k] === null || typeof v[k] !== 'object');
        if (ks.length >= 3 && ks.length === Object.keys(v).length && worded(ks.map(k => String(v[k])))) add('O' + ks.sort().map(k => k + '=' + v[k]).join('\u0001'), Math.max(0, src.indexOf('"' + ks[0] + '"')), JSON.stringify(v).slice(0, 80));
        Object.values(v).forEach(walk); } };
    walk(j); return out;
  }
  const code = src.replace(/\/\*[\s\S]*?\*\//g, c => c.replace(/[^\n]/g, ' '));
  for (const m of code.matchAll(ARR)) { const vs = [...m[1].matchAll(new RegExp(LIT, 'g'))].map(x => unq(x[0])); if (worded(vs)) add('A' + vs.join('\u0001'), m.index, m[0].slice(0, 80)); }
  for (const m of code.matchAll(OBJ)) { const kv = [...m[1].matchAll(new RegExp(String.raw`([\w$]+|'[^'\n]*'|"[^"\n]*")\s*:\s*(${LIT})`, 'g'))].map(x => unq(x[1]) + '=' + unq(x[2]));
    if (worded(kv.map(s => s.split('=').slice(1).join('=')))) add('O' + kv.sort().join('\u0001'), m.index, m[0].slice(0, 80)); }
  return out;
}

/* THE ONE LISTS OF FILES: backend/files.json and index.html's FILES. A literal list naming three or more of them anywhere else is a hand copy. */
function fileNames() {
  const gs = new Set(); try { JSON.parse(read('backend/files.json')).forEach(f => { gs.add(f); gs.add(f.replace(/\.gs$/, '')); }); } catch (e) { /* no manifest: no backend names to match, said by check-manifest */ }
  const js = new Set(); const m = /window\.FILES = \[([^\]]*)\]/.exec(read('index.html'));
  if (m) [...m[1].matchAll(/'([^']+)'/g)].forEach(x => { js.add(x[1]); js.add(x[1] + '.js'); js.add('js/' + x[1] + '.js'); });
  return { gs, js };
}
/* data/settings/ holds its own switches (tiers.json's LATER, card-fields.json): subsets with a meaning, the source of those truths. */
const SOURCES = f => f === 'backend/files.json' || f === 'index.html' || f.startsWith('data/settings/');

/* AN ID'S USER-VISIBLE NAME, in the app and backend (the checks' fixture rows are data, not names): `{ id: 'x', … name|label|title: 'Y' }`, or a label map (three or more `x: 'Words'` on one line). */
function labelsIn(f, src) {
  const out = [], spans = generatedSpans(f, src), code = src.replace(/\/\*[\s\S]*?\*\//g, c => c.replace(/[^\n]/g, ' '));
  const add = (id, label, i) => { if (!inSpans(spans, i) && id.length > 1) out.push({ id, label, at: f + ':' + lineOf(src, i) }); };
  for (const m of code.matchAll(/\{\s*(?:id|key):\s*'([\w-]+)',[^{}\n]*?\b(?:name|label|title):\s*'([A-Z][^'\n]{1,40})'/g)) add(m[1], m[2], m.index);
  code.split('\n').forEach((l, n) => { const pairs = [...l.matchAll(/(?:^|[{,]\s*)([a-z][\w-]*|'[a-z][\w-]*'):\s*'([A-Z][a-z][^'\n]{0,38})'/g)];
    if (pairs.length >= 3 && !/\b(?:say|msg|error|title|label|name|text|help|hint|why|what):/.test(pairs.map(p => p[1]).join(' ') + ':')) pairs.forEach(p => add(unq(p[1]), p[2], code.split('\n').slice(0, n).join('\n').length + 1)); });
  return out;
}

function oneTruth() {
  const files = CODE().concat(SETTINGS()), work = [];
  /* FACTS: each distinct literal list or settings object; it follows the rule when it is written in one file. */
  const facts = new Map();
  files.forEach(f => factsIn(f, read(f)).forEach(x => { if (!facts.has(x.key)) facts.set(x.key, new Map()); const at = facts.get(x.key); if (!at.has(f)) at.set(f, x); }));
  let factsOk = 0;
  facts.forEach(at => { if (at.size < 2) { factsOk++; return; } const xs = [...at.values()];
    work.push({ kind: 'truth-facts', part: 'code', where: xs[0].at, say: `${xs[0].show} is written in ${at.size} files: ${xs.map(x => x.at).join(', ')}` }); });
  /* FILE LISTS: every literal list naming three or more served files; the sources (and generated copies) follow, the rest are hand copies. */
  const N = fileNames(); let lists = 0, listsOk = 0;
  files.forEach(f => { const src = read(f), spans = generatedSpans(f, src);
    const scan = src.replace(/\/\*[\s\S]*?\*\//g, c => c.replace(/[^\n]/g, ' '));
    for (const m of scan.matchAll(/\[([^\[\]]{20,})\]/g)) { const vs = [...m[1].matchAll(/'([^'\n]+)'|"([^"\n]+)"/g)].map(x => x[1] || x[2]);
      const gs = vs.filter(v => N.gs.has(v)).length, js = vs.filter(v => N.js.has(v)).length; if ((gs < 3 && js < 3) || Math.max(gs, js) < vs.length * 0.6) continue;
      lists++; if (SOURCES(f) || inSpans(spans, m.index)) { listsOk++; continue; }
      work.push({ kind: 'truth-lists', part: 'code', where: f + ':' + lineOf(src, m.index), say: `names ${Math.max(gs, js)} ${gs >= js ? 'backend' : 'app'} files by hand — read ${gs >= js ? 'backend/files.json (tools/file-lists.js)' : "index.html's FILES"}` }); } });
  /* ID LABELS: each id given a user-visible name; it follows when every name it is given is in one file. */
  const ids = new Map();
  CODE().filter(f => !/^(?:check\/|js\/check|tools\/)/.test(f)).forEach(f => labelsIn(f, read(f)).forEach(x => { if (!ids.has(x.id)) ids.set(x.id, new Map()); const at = ids.get(x.id); if (!at.has(f)) at.set(f, x); }));
  let idsOk = 0;
  /* A COPIED NAME is the same words for the same id in two files; two different names may be two different things (a role, a group). */
  ids.forEach((at, id) => { const xs = [...at.values()], copied = xs.filter(x => xs.some(y => y !== x && y.label === x.label));
    if (copied.length < 2) { idsOk++; return; }
    work.push({ kind: 'truth-labels', part: 'code', where: xs[0].at, say: `'${id}' is given the same name in ${copied.length} files: ${copied.map(x => `"${x.label}" ${x.at}`).join(', ')}` }); });
  const rule = (id, label, ok, of, unit) => ({ id, group: 'code', label, ok, of, kinds: [id], unit });
  return { work, rules: [rule('truth-facts', 'Lists and settings written in one file only', factsOk, facts.size, 'distinct facts'),
    rule('truth-lists', 'File lists that are the one list (files.json, FILES) or generated from it', listsOk, lists, 'file lists'),
    rule('truth-labels', 'Ids whose user-visible name is written in one file', idsOk, ids.size, 'labelled ids')].filter(r => r.of > 0) };
}
module.exports = { oneTruth };

if (require.main === module) {
  const T = oneTruth(), kind = (process.argv.indexOf('--kind') > 0 ? process.argv[process.argv.indexOf('--kind') + 1] : '');
  T.rules.forEach(r => console.log(`${r.id}: ${r.ok}/${r.of} ${r.unit} — ${r.label}`));
  T.work.filter(w => !kind || w.kind === kind).forEach(w => console.log(`  ${w.kind}  ${w.where}  ${w.say}`));
}
