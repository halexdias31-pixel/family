#!/usr/bin/env node
/* EVERY ACTION FROM ONE FILE (owner, 17 Nov): data/settings/actions.json → permissions.json and the generated blocks Apps Script reads (it cannot read the repo): */
/* ACTION_ACCESS and RUNNABLE (access.gs), postActions_ (dopost.gs), payloadFeatures_ (get-start.gs), PERMISSIONS and ITEM_PERMISSIONS (booking.gs). */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'data', 'settings', 'permissions.json');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const ACTIONS = JSON.parse(read('data/settings/actions.json'));
/* THE PERMISSION TIERS, lowest first: settings.json `roles.tiers`. */
const ROLES = JSON.parse(read('data/settings/settings.json')).roles.tiers;
const POSTS = ACTIONS.actions.filter(a => !a.run), RUNS = ACTIONS.actions.filter(a => a.run);
const S_ = v => (v == null ? '' : String(v));

/* ONE GENERATED BLOCK IN A .gs FILE, replaced where it is, else appended. */
const BEGIN = n => '/* ---------- ' + n + ' (generated) ---------- */\n', END = n => '/* ---------- END ' + n + ' ---------- */\n';
function blockInto(file, name, body) {
  const src = read(file), b = BEGIN(name), e = END(name), i = src.indexOf(b), j = src.indexOf(e);
  const block = b + '/* GENERATED by tools/permissions.js from data/settings/actions.json: edit the json, never this. */\n' + body + e;
  const out = i !== -1 && j > i ? src.slice(0, i) + block + src.slice(j + e.length) : src.replace(/\n*$/, '\n\n') + block;
  fs.writeFileSync(path.join(ROOT, file), out);
}

/* THE GATE'S LEVEL: anyone, self (signed in) or admin. */
const levelOf = roles => roles.indexOf('anyone') !== -1 ? 'anyone' : roles.indexOf('member') !== -1 ? 'self' : roles.indexOf('admin') !== -1 ? 'admin' : '';

/* THE ITEM ROWS: each action's `items`, then the file's own (`via` a door that is not an action). A kind's `anyone` read follows kinds.json `see.who`. */
function itemRows() {
  const kinds = JSON.parse(read('data/settings/kinds.json')).kinds || {}, rows = [], at = {};
  /* ONE ROW PER kind:verb AND TIER: where two actions mirror one kind:verb, the one that allows it is its `via`. */
  const add = (via, items) => Object.keys(items || {}).forEach(kv => ROLES.forEach(role => {
    let allow = items[kv].indexOf(role) !== -1;
    const m = role === 'anyone' && /^(\w+):read$/.exec(kv), see = m && kinds[m[1]] && kinds[m[1]].see;
    if (see && see.who) allow = S_(see.who).split(',').map(x => x.trim()).indexOf('anyone') !== -1;
    const k = kv + ' ' + role;
    if (!at[k]) rows.push(at[k] = { kind: 'item', role, action: kv, allow, via });
    else if (allow && !at[k].allow) Object.assign(at[k], { allow, via });
  }));
  POSTS.forEach(a => add(a.name, a.items));
  Object.keys(ACTIONS.items || {}).forEach(via => add(via, ACTIONS.items[via]));
  return rows;
}

/* permissions.json: the action rows and the item rows from actions.json; the `see` and `ui` rows are the file's own, kept as they are. */
function jsonRows() {
  const acts = [];
  POSTS.slice().sort((a, b) => (a.name < b.name ? -1 : 1)).forEach(a => ROLES.forEach(role =>
    acts.push({ kind: 'action', role, action: a.name, allow: a.roles.indexOf(role) !== -1 })));
  let own = [];
  try { own = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8')).filter(r => r && (r.kind === 'see' || r.kind === 'ui')); } catch (e) { own = []; }
  return acts.concat(own, itemRows());
}

const q = s => "'" + s + "'";
function accessGs() {
  return '/* WHO MAY POST EACH ACTION: anyone, self (signed in; the handler checks whose row) or admin. */\n'
    + 'const ACTION_ACCESS = {\n' + POSTS.map(a => '  ' + a.name + ': ' + q(levelOf(a.roles)) + ',').join('\n') + '\n};\n\n'
    + '/* A JOB FROM A URL (`?run=<job>&arg=…`), for an admin who proves name and PIN (getRun_). */\n'
    + 'const RUNNABLE = {\n' + RUNS.map(a => '  ' + a.name + ': ' + (a.arg ? 'a => ' + a.handler + '(a)' : '() => ' + a.handler + '()') + ',').join('\n') + '\n};\n';
}
function dopostGs() {
  return '/* EVERY ACTION BY NAME → its handler (backend/post-*.gs). An action with no handler here answers `Unknown action`. */\n'
    + 'function postActions_() {\n  return {\n' + POSTS.filter(a => a.handler).map(a => '    ' + a.name + ': ' + a.handler + ',').join('\n') + '\n  };\n}\n';
}
function featuresGs() {
  const f = POSTS.filter(a => a.feature).map(a => a.name).concat(ACTIONS.features || []);
  return '/* WHAT THIS DEPLOY CAN DO, by action name: the site compares it against what it needs. */\n'
    + 'function payloadFeatures_() {\n  return [' + f.map(q).join(', ') + '];\n}\n';
}
function bookingGs(rows) {
  const by = {}, it = {};
  POSTS.forEach(a => { by[a.name] = a.roles.slice(); });
  rows.filter(r => r.kind === 'item' && r.allow === true).forEach(r => { (it[r.action] = it[r.action] || {})[r.role] = true; });
  return '/* Each action\'s allowed tiers: anyone (signed out), member (signed in), child, admin. Not listed → refused. */\n'
    + 'const PERMISSIONS = {\n' + Object.keys(by).sort().map(a => '  ' + a + ': [' + by[a].map(q).join(', ') + '],').join('\n') + '\n};\n\n'
    + '/* THE GATE\'S LEVEL FOR AN ACTION: anyone, self or admin; \'\' refuses it. */\n'
    + 'function permNeed_(action) {\n'
    + '  return Object.prototype.hasOwnProperty.call(ACTION_ACCESS, action) ? ACTION_ACCESS[action] : \'\';\n'
    + '}\n\n'
    + '/* A CHILD REFUSED WHAT A MEMBER MAY DO (398, money): the action\'s tiers name member and not child. */\n'
    + 'function permChildDenied_(action) {\n'
    + '  const r = Object.prototype.hasOwnProperty.call(PERMISSIONS, action) ? PERMISSIONS[action] : null;\n'
    + "  return !!r && r.indexOf('member') !== -1 && r.indexOf('child') === -1;\n"
    + '}\n\n'
    + '/* Each item kind:verb → the tiers allowed. Not listed → refused. */\n'
    + 'const ITEM_PERMISSIONS = {\n' + Object.keys(it).sort().map(a => "  '" + a + "': [" + ROLES.filter(r => it[a][r]).map(q).join(', ') + '],').join('\n') + '\n};\n\n'
    + '/* WHETHER THIS TIER MAY kind:verb. */\n'
    + 'function itemMay_(kind, verb, role) {\n'
    + "  const r = Object.prototype.hasOwnProperty.call(ITEM_PERMISSIONS, kind + ':' + verb) ? ITEM_PERMISSIONS[kind + ':' + verb] : null;\n"
    + '  return !!r && r.indexOf(role) !== -1;\n'
    + '}\n';
}

module.exports = { ROLES, ACTIONS, levelOf, jsonRows };
if (require.main === module) {
  const rows = jsonRows();
  fs.writeFileSync(JSON_PATH, '[\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n]\n');
  blockInto('backend/access.gs', 'ACTIONS', accessGs());
  blockInto('backend/dopost.gs', 'ACTIONS', dopostGs());
  blockInto('backend/get-start.gs', 'FEATURES', featuresGs());
  blockInto('backend/booking.gs', 'PERMISSIONS', bookingGs(rows));
  console.log('permissions: ' + rows.length + ' rows to permissions.json; ' + POSTS.length + ' actions and ' + RUNS.length + ' jobs into access.gs, dopost.gs, get-start.gs and booking.gs');
}
