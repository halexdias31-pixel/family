#!/usr/bin/env node
/* EVERY ACTION FROM ONE FILE (owner, 17 Nov): data/settings/actions.json → permissions.json and the generated blocks Apps Script reads (it cannot read the repo): */
/* RUNNABLE (access.gs), postActions_ (dopost.gs), payloadFeatures_ (get-start.gs), PERMISSIONS and ITEM_PERMISSIONS (booking.gs). */
'use strict';
const fs = require('fs'), path = require('path');
const { ROOT, read, S, blockInto, writeIfChanged } = require('./lib/gen');
const JSON_PATH = path.join(ROOT, 'data', 'settings', 'permissions.json');
const ACTIONS = read('data/settings/actions.json');
/* THE PERMISSION TIERS, lowest first: settings.json `roles.tiers`. */
const ROLES = read('data/settings/settings.json').roles.tiers;
const RUNS = ACTIONS.actions.filter(a => a.run);

/* ONE GENERATED BLOCK IN A .gs FILE, replaced where it is, else appended. */
const BEGIN = n => '/* ---------- ' + n + ' (generated) ---------- */\n', END = n => '/* ---------- END ' + n + ' ---------- */\n';
function blockFile_(file, name, body) {
  const at = path.join(ROOT, file);
  writeIfChanged(at, blockInto(fs.readFileSync(at, 'utf8'), BEGIN(name), END(name),
    '/* GENERATED by tools/permissions.js from data/settings/actions.json: edit the json, never this. */\n' + body));
}

/* THE GATE'S LEVEL: anyone, self (signed in) or admin. */
const levelOf = roles => roles.indexOf('anyone') !== -1 ? 'anyone' : roles.indexOf('member') !== -1 ? 'self' : roles.indexOf('admin') !== -1 ? 'admin' : '';

/* THE ITEM ROWS: actions.json `items`, each kind:verb × tier. A kind's `anyone` read follows kinds.json `see.who`. */
function itemRows() {
  const kinds = read('data/settings/kinds.json').kinds || {}, rows = [];
  Object.keys(ACTIONS.items).forEach(kv => ROLES.forEach(role => {
    let allow = ACTIONS.items[kv].roles.indexOf(role) !== -1;
    const m = role === 'anyone' && /^(\w+):read$/.exec(kv), see = m && kinds[m[1]] && kinds[m[1]].see;
    if (see && see.who) allow = S(see.who).split(',').map(x => x.trim()).indexOf('anyone') !== -1;
    rows.push({ kind: 'item', role, action: kv, allow });
  }));
  return rows;
}

/* AN OLD NAME KEPT AS AN ALIAS (step 6, 22 Nov): a row with `item` (kind:verb) takes that item's handler, and its tiers from the item's */
/* rows in the table (itemRows), so a merged name is gated, and answered, exactly as its kind:verb is. tools/one-action-roles.js holds it to its old tiers. */
const ITEM_ALLOWED = {};
itemRows().forEach(r => { if (r.allow) (ITEM_ALLOWED[r.action] = ITEM_ALLOWED[r.action] || []).push(r.role); });
const POSTS = ACTIONS.actions.filter(a => !a.run).map(a => {
  if (!a.item) return a;
  const it = ACTIONS.items[a.item];
  if (!it || !it.handler) throw new Error('actions.json: ' + a.name + ' names item ' + a.item + ', which has no handler');
  return Object.assign({}, a, { handler: it.handler, roles: (ITEM_ALLOWED[a.item] || []).slice() });
});

/* permissions.json: the action rows and the item rows from actions.json; the `see` and `ui` rows are the file's own, kept as they are. */
function jsonRows() {
  const acts = [];
  POSTS.slice().sort((a, b) => (a.name < b.name ? -1 : 1)).forEach(a => ROLES.forEach(role =>
    acts.push({ kind: 'action', role, action: a.name, allow: a.roles.indexOf(role) !== -1 })));
  let own = [];
  try { own = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8')).filter(r => r && (r.kind === 'see' || r.kind === 'ui')); } catch (e) { own = []; }
  return acts.concat(own, itemRows());
}

const q = s => "'" + s + "'";
function accessGs() {
  return '/* A JOB FROM A URL (`?run=<job>&arg=…`), for an admin who proves name and PIN (getRun_). */\n'
    + 'const RUNNABLE = {\n' + RUNS.map(a => '  ' + a.name + ': ' + (a.arg ? 'a => ' + a.handler + '(a)' : '() => ' + a.handler + '()') + ',').join('\n') + '\n};\n';
}
function dopostGs() {
  return '/* EVERY ACTION BY NAME → its handler (backend/post-*.gs). An action with no handler here answers `Unknown action`. */\n'
    + 'function postActions_() {\n  return {\n' + POSTS.filter(a => a.handler).map(a => '    ' + a.name + ': ' + (a.item ? "(b, a, g) => " + a.handler + "(b, '" + a.item + "', g)" : a.handler) + ',').join('\n') + '\n  };\n}\n';
}
const DOORS = Object.keys(ACTIONS.items).filter(kv => ACTIONS.items[kv].handler || ACTIONS.items[kv].other);
function featuresGs() {
  /* THE ACTIONS FLAGGED `feature`, every kind:verb the item door answers, and the file's own words. */
  const f = POSTS.filter(a => a.feature).map(a => a.name).concat(DOORS, ACTIONS.features || []);
  return '/* WHAT THIS DEPLOY CAN DO, by action name: the site compares it against what it needs. */\n'
    + 'function payloadFeatures_() {\n  return [' + f.map(q).join(', ') + '];\n}\n';
}
function bookingGs(rows) {
  const by = {}, it = {};
  POSTS.forEach(a => { by[a.name] = a.roles.slice(); });
  rows.filter(r => r.kind === 'item' && r.allow === true).forEach(r => { (it[r.action] = it[r.action] || {})[r.role] = true; });
  return '/* Each action\'s allowed tiers: anyone (signed out), member (signed in), child, admin. Not listed → refused. */\n'
    + 'const PERMISSIONS = {\n' + Object.keys(by).sort().map(a => '  ' + a + ': [' + by[a].map(q).join(', ') + '],').join('\n') + '\n};\n\n'
    + '/* THE GATE\'S LEVEL FOR AN ACTION: anyone, self or admin; \'\' refuses it. */\n'
    + 'function permNeed_(action) {\n'
    + '  return Object.prototype.hasOwnProperty.call(PERMISSIONS, action) ? levelOf_(PERMISSIONS[action]) : \'\';\n'
    + '}\n\n'
    + '/* THE LEVEL FROM THE TIERS (tools/permissions.js `levelOf`, the same words): anyone, self (signed in; the handler checks whose row) or admin. */\n'
    + 'function levelOf_(roles) {\n'
    + "  return roles.indexOf('anyone') !== -1 ? 'anyone' : roles.indexOf('member') !== -1 ? 'self' : roles.indexOf('admin') !== -1 ? 'admin' : '';\n"
    + '}\n\n'
    + '/* A CHILD REFUSED WHAT A MEMBER MAY DO (398, money): the action\'s tiers name member and not child. */\n'
    + 'function permChildDenied_(action) {\n'
    + '  const r = Object.prototype.hasOwnProperty.call(PERMISSIONS, action) ? PERMISSIONS[action] : null;\n'
    + "  return !!r && r.indexOf('member') !== -1 && r.indexOf('child') === -1;\n"
    + '}\n\n'
    + '/* Each item kind:verb → the tiers allowed. Not listed → refused. */\n'
    + 'const ITEM_PERMISSIONS = {\n' + Object.keys(it).sort().map(a => "  '" + a + "': [" + ROLES.filter(r => it[a][r]).map(q).join(', ') + '],').join('\n') + '\n};\n\n'
    + '/* WHETHER THIS TIER MAY kind:verb. */\n'
    + 'function itemMay_(kind, verb, role) {\n'
    + "  const r = Object.prototype.hasOwnProperty.call(ITEM_PERMISSIONS, kind + ':' + verb) ? ITEM_PERMISSIONS[kind + ':' + verb] : null;\n"
    + '  return !!r && r.indexOf(role) !== -1;\n'
    + '}\n\n'
    + '/* WHAT THE ITEM DOOR ANSWERS kind:verb WITH: `self` your own, `other` an admin asking after somebody else (`logged` leaves a lens_log row, `blank` may name nobody). */\n'
    + 'function itemDoors_() {\n  return {\n' + DOORS.map(kv => {
      const e = ACTIONS.items[kv], parts = [];
      /* THE HANDLER IS HANDED kind:verb (step 6, 22 Nov), by this door and by the old name alike (dopostGs). */
      if (e.handler) parts.push('self: ' + e.handler);
      if (e.other) parts.push('other: ' + e.other);
      if (e.logged) parts.push('logged: true');
      if (e.blank) parts.push('blank: true');
      return "    '" + kv + "': { " + parts.join(', ') + ' },';
    }).join('\n') + '\n  };\n}\n';
}

function run() {
  const rows = jsonRows();
  writeIfChanged(JSON_PATH, '[\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n]\n');
  blockFile_('backend/access.gs', 'ACTIONS', accessGs());
  blockFile_('backend/dopost.gs', 'ACTIONS', dopostGs());
  blockFile_('backend/get-start.gs', 'FEATURES', featuresGs());
  blockFile_('backend/booking.gs', 'PERMISSIONS', bookingGs(rows));
  console.log('permissions: ' + rows.length + ' rows to permissions.json; ' + POSTS.length + ' actions and ' + RUNS.length + ' jobs into access.gs, dopost.gs, get-start.gs and booking.gs');
}
module.exports = { ROLES, ACTIONS, POSTS, RUNS, levelOf, jsonRows, run };
if (require.main === module) run();
