#!/usr/bin/env node
/* THE ONE PERMISSIONS TABLE (86a): data/settings/permissions.json from ACTION_ACCESS and KID_MONEY_ACTIONS, then a generated block in backend/booking.gs beside accessDenied — Apps Script cannot read the repo. */
/* `--from-access` rebuilds the JSON from the backend; plain run writes the .gs from the JSON; `--check` only compares both. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'data', 'settings', 'permissions.json');
const GS_PATH = path.join(ROOT, 'backend', 'booking.gs');
const BEGIN = '/* ---------- PERMISSIONS (generated) ---------- */\n', END = '/* ---------- END PERMISSIONS ---------- */\n';
/* THE FILE WITH ITS BLOCK AS IT SHOULD BE: replaced where it is, else appended. */
function gsInto(src, rows) {
  const block = BEGIN + gsText(rows) + END, a = src.indexOf(BEGIN), b = src.indexOf(END);
  return a !== -1 && b > a ? src.slice(0, a) + block + src.slice(b + END.length) : src.replace(/\n*$/, '\n\n') + block;
}
const ROLES = ['anyone', 'member', 'child', 'admin'];
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const strip = t => t.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:\\])\/\/.*$/gm, '$1');

/* ACTION_ACCESS as {action: level}, KID_MONEY_ACTIONS as a list — read off the source, as check-actions does. */
function backendRules() {
  const c = read('backend/constants.gs'), t = c.slice(c.indexOf('const ACTION_ACCESS = {'));
  const access = {};
  for (const m of strip(t.slice(0, t.indexOf('\n};'))).matchAll(/(\w+)\s*:\s*'(\w+)'/g)) access[m[1]] = m[2];
  const k = /const KID_MONEY_ACTIONS = \[([^\]]*)\]/.exec(read('backend/people.gs'));
  const kid = k ? [...k[1].matchAll(/'(\w+)'/g)].map(x => x[1]) : [];
  return { access, kid };
}

/* WHAT A LEVEL ALLOWS EACH ROLE: the gate's three levels, then the child-money rule taken off `member`'s yes. */
function allowOf(level, role, kidMoney) {
  if (level === 'anyone') return true;
  if (level === 'self') return role === 'child' ? !kidMoney : role !== 'anyone';
  if (level === 'admin') return role === 'admin';
  return false;
}

function rowsFromAccess() {
  const { access, kid } = backendRules(), rows = [];
  Object.keys(access).sort().forEach(a => ROLES.forEach(role =>
    rows.push({ kind: 'action', role, action: a, allow: allowOf(access[a], role, kid.indexOf(a) !== -1) })));
  return rows;
}

function jsonText(rows) { return '[\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n]\n'; }

/* THE .gs: each action's allowed roles, and the two readers accessDenied and doPost's child rule ask. */
function gsText(rows) {
  const by = {};
  rows.filter(r => r && r.kind === 'action').forEach(r => { by[r.action] = by[r.action] || []; if (r.allow === true) by[r.action].push(r.role); });
  return '/* GENERATED by tools/permissions.js from data/settings/permissions.json (86a): re-run it, never edit by hand. */\n'
    + '/* Each action\'s allowed roles: anyone (signed out), member (signed in), child, admin. Not listed → ACTION_ACCESS decides. */\n'
    + 'const PERMISSIONS = {\n' + Object.keys(by).sort().map(a => '  ' + a + ': [' + by[a].map(r => "'" + r + "'").join(', ') + '],').join('\n') + '\n};\n\n'
    + '/* THE GATE\'S LEVEL FOR AN ACTION, read off the table: anyone, self or admin; \'\' refuses it. */\n'
    + 'function permNeed_(action) {\n'
    + '  const r = Object.prototype.hasOwnProperty.call(PERMISSIONS, action) ? PERMISSIONS[action] : null;\n'
    + '  if (!r) return ACTION_ACCESS[action];\n'
    + "  if (r.indexOf('anyone') !== -1) return 'anyone';\n"
    + "  if (r.indexOf('member') !== -1) return 'self';\n"
    + "  return r.indexOf('admin') !== -1 ? 'admin' : '';\n"
    + '}\n\n'
    + '/* A CHILD REFUSED WHAT A MEMBER MAY DO (398, money): the table\'s child row, else KID_MONEY_ACTIONS. */\n'
    + 'function permChildDenied_(action) {\n'
    + '  const r = Object.prototype.hasOwnProperty.call(PERMISSIONS, action) ? PERMISSIONS[action] : null;\n'
    + "  if (!r) return KID_MONEY_ACTIONS.indexOf(action) !== -1;\n"
    + "  return r.indexOf('member') !== -1 && r.indexOf('child') === -1;\n"
    + '}\n';
}

module.exports = { ROLES, backendRules, allowOf, rowsFromAccess, gsText, gsInto, GS_PATH };
if (require.main === module) {
  const want = process.argv.includes('--from-access') || !fs.existsSync(JSON_PATH) ? jsonText(rowsFromAccess()) : fs.readFileSync(JSON_PATH, 'utf8');
  const cur = fs.readFileSync(GS_PATH, 'utf8'), gs = gsInto(cur, JSON.parse(want));
  if (process.argv.includes('--check')) {
    const okJ = fs.existsSync(JSON_PATH) && fs.readFileSync(JSON_PATH, 'utf8') === jsonText(rowsFromAccess());
    const okG = cur === gsInto(cur, JSON.parse(fs.readFileSync(JSON_PATH, 'utf8')));
    console.log((okJ ? 'permissions.json current' : 'permissions.json STALE against ACTION_ACCESS — node tools/permissions.js --from-access')
      + '; ' + (okG ? 'booking.gs block current' : 'booking.gs PERMISSIONS block STALE — node tools/permissions.js'));
    process.exit(okJ && okG ? 0 : 1);
  }
  fs.writeFileSync(JSON_PATH, want);
  fs.writeFileSync(GS_PATH, gs);
  console.log('wrote ' + JSON.parse(want).length + ' rows to data/settings/permissions.json and the block in backend/booking.gs');
}
