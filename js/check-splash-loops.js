#!/usr/bin/env node
/* ==================================================================================================
   @family. — check-splash-loops.js

   THE LOADING SPLASHES THAT WERE REBUILT AS ONE SEAMLESS LOOP, READ OFF THE FILES.

   ASKED FOR AS "refine the pythagoras animation", "refine the pi circle animation. make it better."
   and "refine indicies loading animation". All three had the same three faults, measured on the
   real page before anything was changed:

     A WIPE ON THE SUBJECT   Pythagoras ran a dash 12 long round a triangle 12 long, so once every
                             2.6s the triangle the proof is about vanished.
     A SNAP AT THE SEAM      the indices' second group jumped 22px and the × popped back in one
                             frame at 100% → 0%, because two keyframes had no return leg.
     TWO CLOCKS              the indices counted the tiles on one timeline and joined them on
                             another, so the last two lit up after the groups had parted again.

   And a fourth that only the circle had: a cross-fade, so nothing ever MOVED from the circle into
   the strip, which is the whole argument.

   `npm run splash` cannot catch any of these. It asks whether the picture changes between frames,
   and a wipe, a snap and a cross-fade all change the picture. They are properties of the
   keyframes, so this reads the keyframes:

     · every animation in the splash is infinite and has the splash's one duration — ONE timeline,
       so nothing can drift out of step and index.html's replay loop never restarts half of it;
     · every keyframe it uses ends where it began (the 0% and 100% stops say the same thing, or
       neither is written), so the loop has no seam;
     · only `transform` and `opacity` move — the compositor's two, which keep moving while the
       main thread parses the app;
     · nothing in it draws with a dash, which is how the triangle was wiped;
     · reduced motion turns every one of those animations off;
     · the drawing is centred in its viewBox and inside it, so it sits over its caption and nothing
       is clipped at 320 wide.

   Then each splash has its own sentence, below, for the one thing that makes it that proof. Two
   have joined since — the angle at the centre ("refine the circle theorems animation") and y = mx + c
   ("refine the gradiant animation") — and both are generated by a script in tools/ whose positions
   this re-derives from the keyframes rather than trusting.

     node js/check-splash-loops.js
================================================================================================== */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');

/* ---------- WHICH SPLASHES, AND WHAT EACH ONE PROMISES -------------------------------------------
   A LIST, BECAUSE THESE ARE THE ONES BUILT TO THIS STANDARD. The other splashes in the pool were
   written before it and several deliberately hold or fade; holding them to a seam they never
   promised would fill this report with red nobody asked for, and a red nobody reads is how a new
   one gets in. A splash joins the list when it is rebuilt to the standard. */
const LOOPS = [
  { id: 'pyth', prefix: 'py-', centreOn: ['py-edge'],
    own: pythOwn_ },
  { id: 'area', prefix: 'ar-', centreOn: ['ar-ring', 'ar-slot'],
    own: areaOwn_ },
  /* NO viewBox: the index laws are tiles in a flex row, centred by `justify-content`, so the
     centring sentence is in indexOwn_ — each group moves half the distance. */
  { id: 'index', prefix: 'ix-',
    own: indexOwn_ },
  /* THE RING: centred on its two corner posts, which the generator places symmetrically. */
  { id: 'box', prefix: 'bx-', centreOn: ['bx-post'],
    own: boxOwn_ },  /* THE ANGLE AT THE CENTRE: centred on its rim, which tools/cent.py places in the box's middle. */
  { id: 'cent', prefix: 'ct-', centreOn: ['ct-rim'],
    own: centOwn_ },
  /* y = mx + c: centred on its two axes, which tools/mxc.py lays so the plot is the middle of the box
     — the y-axis is left of centre on purpose, because the triangle is right of it. Its line ends the
     loop HALF A TURN on from where it began: it swings on over the vertical rather than back through
     the stops it has named, and a line through its own pivot is the same line half a turn later.
     `halfTurn` lets that keyframe's seam differ by a multiple of 180° and nothing else; mxcOwn_ is
     what proves the line is drawn symmetric about its pivot, which is what makes that true. */
  { id: 'mxc', prefix: 'mx-', centreOn: ['mx-ax', 'mx-ay', 'mx-arrow'], halfTurn: ['mx-line'],
    own: mxcOwn_ },
];

let faults = [], said = [];
const fault = (id, s) => faults.push('#splash-' + id + '  ' + s);

let html, css;
try {
  html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  css = fs.readFileSync(path.join(ROOT, 'style.css'), 'utf8');
} catch (e) {
  /* A CHECK THAT CANNOT REACH ITS SUBJECT SAYS SO AND EXITS NON-ZERO. */
  console.log('COULD NOT RUN — index.html or style.css is missing: ' + e.message);
  process.exit(1);
}

/* ---------- THE STYLESHEET, READ AS BLOCKS --------------------------------------------------------
   A small brace walker rather than a regex: a regex that stops at the first `}` reads the first
   STOP of a keyframes block as the whole block, which is the fault check-css.js records twice.
   Comments are blanked first, keeping their newlines, so a brace in prose is not a brace. */
const bare = css.replace(/\/\*[\s\S]*?\*\//g, m => m.replace(/[^\n]/g, ' '));
const rules = [];          // { sel, decls: {prop: val}, media }
const frames = {};         // name -> [{ keys: [0..100], decls }]
(function walk(src, media) {
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open < 0) break;
    const head = src.slice(i, open).trim().replace(/\s+/g, ' ');
    let depth = 1, j = open + 1;
    while (j < src.length && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; j++; }
    const body = src.slice(open + 1, j - 1);
    const decls_ = b => {
      const out = {};
      b.split(';').forEach(d => { const k = d.indexOf(':'); if (k > 0) out[d.slice(0, k).trim()] = d.slice(k + 1).trim().replace(/\s+/g, ' '); });
      return out;
    };
    if (/^@keyframes\s/.test(head)) {
      const name = head.split(/\s+/)[1];
      const stops = [];
      const re = /([^{}]+)\{([^{}]*)\}/g; let m;
      while ((m = re.exec(body))) {
        const keys = m[1].split(',').map(k => k.trim()).map(k => k === 'from' ? 0 : k === 'to' ? 100 : parseFloat(k));
        stops.push({ keys, decls: decls_(m[2]) });
      }
      frames[name] = stops;
    } else if (/^@(media|supports)/.test(head)) {
      walk(body, head);
    } else if (!head.startsWith('@')) {
      rules.push({ sel: head, decls: decls_(body), media });
    }
    i = j;
  }
})(bare, '');

const isStill = r => /prefers-reduced-motion:\s*reduce/.test(r.media);
const parts = sel => sel.split(',').map(s => s.trim());

/* TWO TRANSFORMS THAT DRAW THE SAME LINE: equal once every rotate() is taken modulo 180°, and only for
   keyframes a splash names in `halfTurn`. Anything else that differs — a translate, a scale — is still
   a seam. */
const halfTurn_ = (a, b) => {
  if (a === undefined || b === undefined) return false;
  const norm = s => s.replace(/rotate\((-?\d*\.?\d+)deg\)/g, (_, d) => 'rotate(' + ((+d % 180 + 180) % 180).toFixed(3) + 'deg)');
  return norm(a) === norm(b);
};

/* ---------- THE MARKUP OF ONE SPLASH -------------------------------------------------------------
   From its opening tag to the `</div>` at the splash's own indent — the same boundary the
   generators in tools/ replace, so this reads exactly what they write. */
function markup_(id) {
  const a = html.indexOf('<div id="splash-' + id + '"');
  if (a < 0) return null;
  const b = html.indexOf('\n  </div>', a);
  return b < 0 ? null : html.slice(a, b);
}

/* ---------- THE CORNERS OF A PATH ----------------------------------------------------------------
   Absolute M, L, H, V and the endpoints of A — what the generators write. An arc's bulge is not
   counted, so a box built from these can only be smaller than the drawing, never larger: the
   centring test asks about the frame the generator drew to centre on, which is straight-sided. */
function pathPoints_(d) {
  const pts = [];
  const tok = d.match(/[MLHVAZmlhvaz]|-?\d*\.?\d+(?:e-?\d+)?/g) || [];
  let cmd = '', x = 0, y = 0, k = 0;
  while (k < tok.length) {
    const t = tok[k];
    if (/[A-Za-z]/.test(t)) { cmd = t; k++; if (/[Zz]/.test(cmd)) continue; }
    const n = () => parseFloat(tok[k++]);
    if (cmd === 'M' || cmd === 'L') { x = n(); y = n(); }
    else if (cmd === 'H') x = n();
    else if (cmd === 'V') y = n();
    else if (cmd === 'A') { n(); n(); n(); n(); n(); x = n(); y = n(); }
    else { k++; continue; }                      // a relative command: not written here, skipped
    pts.push([x, y]);
  }
  return pts;
}

for (const L of LOOPS) {
  const m = markup_(L.id);
  if (!m) { fault(L.id, 'is not in index.html — the check cannot reach it'); continue; }

  const mine = rules.filter(r => parts(r.sel).some(p => p.includes('#splash-' + L.id) || p.includes('.' + L.prefix)));
  if (!mine.length) { fault(L.id, 'has no rules in style.css with .' + L.prefix + ' — nothing to read'); continue; }

  /* ---- A DASH IS A WIPE. Pythagoras's triangle was erased by one. ---- */
  mine.filter(r => !isStill(r)).forEach(r => Object.keys(r.decls).forEach(p => {
    if (/^stroke-dash/.test(p)) fault(L.id, r.sel + ' sets ' + p + ' — a dash moving round an outline is a wipe that erases it');
  }));

  /* ---- ONE TIMELINE, AND IT NEVER ENDS ---- */
  const durations = new Set(), animated = [];
  mine.filter(r => !isStill(r)).forEach(r => {
    const a = r.decls.animation || r.decls['animation-name'];
    if (!a || a === 'none') return;
    animated.push(r);
    /* SPLIT AT THE TOP-LEVEL COMMAS ONLY: `cubic-bezier(.55, 0, .3, 1)` has three of its own, and
       splitting there read one animation as four, three of them nameless. */
    a.split(/,(?![^(]*\))/).forEach(one => {
      const words = one.trim().split(/\s+/);
      const name = words.find(w => frames[w]);
      if (!name) { fault(L.id, r.sel + ' names an animation with no @keyframes: ' + one.trim()); return; }
      const infinite = words.includes('infinite') || r.decls['animation-iteration-count'] === 'infinite';
      if (!infinite) fault(L.id, r.sel + ' runs ' + name + ' a finite number of times — a piece that stops is a piece out of step, and the replay loop never restarts a splash with anything endless in it');
      const dur = words.find(w => /^\d*\.?\d+m?s$/.test(w)) || r.decls['animation-duration'];
      durations.add(dur);
      const stops = frames[name];
      /* ---- TRANSFORM AND OPACITY ONLY ---- */
      stops.forEach(s => Object.keys(s.decls).forEach(p => {
        if (!['transform', 'opacity', 'animation-timing-function'].includes(p))
          fault(L.id, '@keyframes ' + name + ' animates ' + p + ' — only transform and opacity keep moving while the main thread parses the app');
      }));
      /* ---- THE SEAM: 100% SAYS WHAT 0% SAID ---- */
      const at = key => { const o = {}; stops.filter(s => s.keys.includes(key)).forEach(s => Object.assign(o, s.decls)); delete o['animation-timing-function']; return o; };
      const a0 = at(0), a1 = at(100);
      const props = new Set([...Object.keys(a0), ...Object.keys(a1)]);
      props.forEach(p => {
        if (p === 'transform' && (L.halfTurn || []).includes(name) && halfTurn_(a0[p], a1[p])) return;
        if (a0[p] !== a1[p]) fault(L.id, '@keyframes ' + name + ' ends with ' + p + ': ' + (a1[p] || '(the base value)')
          + ' but starts with ' + (a0[p] || '(the base value)') + ' — the loop snaps at 100% → 0%');
      });
    });
  });
  if (!animated.length) fault(L.id, 'animates nothing — a loading screen that holds still reads as an app that has died');
  if (durations.size > 1) fault(L.id, 'runs on ' + durations.size + ' clocks (' + [...durations].join(', ')
    + ') — two durations drift apart over a long load, which is how the indices counted after they had parted');

  /* ---- REDUCED MOTION IS THE FINISHED STILL ---- */
  const off = new Set();
  mine.filter(isStill).forEach(r => { if (/^none\b/.test(r.decls.animation || '')) parts(r.sel).forEach(p => off.add(p)); });
  animated.forEach(r => parts(r.sel).forEach(p => {
    if (!off.has(p)) fault(L.id, p + ' still moves under prefers-reduced-motion — the reduced rule must name it with animation: none');
  }));

  /* ---- CENTRED, AND INSIDE ITS BOX ---- */
  const vb = (m.match(/viewBox="([^"]+)"/) || [])[1];
  if (vb && L.centreOn) {
    const [vx, vy, vw, vh] = vb.split(/[\s,]+/).map(Number);
    const pts = [];
    const re = /<(path|line|circle|rect)\b([^>]*)>/g; let e;
    while ((e = re.exec(m))) {
      const cls = (e[2].match(/class="([^"]+)"/) || [])[1] || '';
      if (!L.centreOn.some(c => cls.split(/\s+/).includes(c))) continue;
      const at = n => { const q = e[2].match(new RegExp('\\s' + n + '="([^"]+)"')); return q ? parseFloat(q[1]) : 0; };
      if (e[1] === 'path') pts.push(...pathPoints_((e[2].match(/\sd="([^"]+)"/) || [])[1] || ''));
      if (e[1] === 'line') pts.push([at('x1'), at('y1')], [at('x2'), at('y2')]);
      if (e[1] === 'circle') { const r = at('r'); pts.push([at('cx') - r, at('cy') - r], [at('cx') + r, at('cy') + r]); }
      if (e[1] === 'rect') pts.push([at('x'), at('y')], [at('x') + at('width'), at('y') + at('height')]);
    }
    if (!pts.length) fault(L.id, 'has nothing with class ' + L.centreOn.join(' or ') + ' to centre on — the check cannot measure it');
    else {
      const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
      const x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(...ys), y1 = Math.max(...ys);
      const off_ = ((x0 + x1) / 2 - (vx + vw / 2)) / vw;
      /* ONE PER CENT OF THE WIDTH is about 2.4px on a 320 phone — under what anybody sees, and well
         under the 9px Pythagoras sat off its caption and the 44px the circle did. */
      if (Math.abs(off_) > .01) fault(L.id, 'is drawn ' + (off_ * 100).toFixed(1) + '% of its width off the centre of its viewBox — it will sit to one side of its caption');
      if (x0 < vx || x1 > vx + vw || y0 < vy || y1 > vy + vh) fault(L.id, 'reaches outside its viewBox (' + [x0, y0, x1, y1].map(v => +v.toFixed(2)).join(' ') + ' against ' + vb + ') — clipped');
    }
  }

  if (L.own) L.own(L, m, mine);
  said.push('#splash-' + L.id + ': ' + animated.length + ' animated rules, ' + [...durations].join('/') + ' timeline');
}

/* ---------- PYTHAGORAS: THE CELLS ARE COUNTED ------------------------------------------------------
   9 cells from the square on the short leg and 16 from the long one, and between them they land on
   25 DIFFERENT places — so the big square is filled exactly, with no slot covered twice and none
   left empty. If two cells shared a --to, the picture would show 25 in the sum over a square with a
   hole in it, and only somebody counting would notice. */
function pythOwn_(L, m) {
  const cells = [...m.matchAll(/<rect class="py-cell (py-[ab])"[^>]*--from: ([^;]+); --to: ([^;]+);/g)];
  const a = cells.filter(c => c[1] === 'py-a').length, b = cells.filter(c => c[1] === 'py-b').length;
  if (a !== 9 || b !== 16) fault(L.id, 'has ' + a + ' + ' + b + ' cells; 3² + 4² is 9 + 16');
  const to = new Set(cells.map(c => c[3])), from = new Set(cells.map(c => c[2]));
  if (to.size !== 25) fault(L.id, 'its cells land on ' + to.size + ' different places, not 25 — the big square would have a hole');
  if (from.size !== 25) fault(L.id, 'its cells start from ' + from.size + ' different places, not 25');
  if (/class="py-tri"[^>]*style=/.test(m) || rules.some(r => parts(r.sel).includes('.py-tri') && r.decls.animation))
    fault(L.id, 'animates the triangle — the triangle is the subject, and the last thing that moved it erased it');
}

/* ---------- THE CIRCLE: THE SLICES TRAVEL, AND THE HALVES ARE THE EDGES ---------------------------
   THE OLD ONE CROSS-FADED, so the first sentence is that every slice has somewhere different to be
   at the end from where it was at the start, and the slices' keyframes move them rather than fade
   them. The second is the colour coding the proof rests on: every gold slice lands arc-up (no
   turn) and every teal one arc-down (half a turn), the same number of each — so the strip's top
   edge is the gold half of the circle and nothing else, which is what makes "πr" true of it. */
function areaOwn_(L, m) {
  const sl = [...m.matchAll(/<path class="ar-sl (ar-top|ar-bot)"[^>]*--from: ([^;]+); --to: ([^;]+);/g)];
  if (!sl.length) { fault(L.id, 'has no .ar-sl slices with a --from and a --to — nothing travels'); return; }
  sl.forEach((s, k) => { if (s[2] === s[3]) fault(L.id, 'slice ' + k + ' ends where it starts — it does not travel'); });
  const top = sl.filter(s => s[1] === 'ar-top'), bot = sl.filter(s => s[1] === 'ar-bot');
  if (top.length !== bot.length) fault(L.id, top.length + ' gold slices and ' + bot.length + ' teal — the halves must match');
  top.forEach(s => { if (!/rotate\(0deg\)$/.test(s[3])) fault(L.id, 'a gold slice lands turned (' + s[3] + ') — the gold arcs must be the top edge'); });
  bot.forEach(s => { if (!/rotate\(180deg\)$/.test(s[3])) fault(L.id, 'a teal slice lands as ' + s[3] + ' — the teal arcs must be the bottom edge'); });
  if (new Set(sl.map(s => s[3])).size !== sl.length) fault(L.id, 'two slices land in the same place');
  const fly = rules.find(r => r.sel === '.ar-sl' && !isStill(r));
  const name = fly && (fly.decls.animation || '').split(/\s+/).find(w => frames[w]);
  if (!name) fault(L.id, '.ar-sl has no animation — the slices do not move');
  else if (frames[name].some(st => 'opacity' in st.decls)) fault(L.id, '@keyframes ' + name + ' fades the slices — a cross-fade is the fault this replaced');
}

/* ---------- THE INDEX LAWS: COUNTED WHILE JOINED, AND JOINED EXACTLY -------------------------------
   THE OLD ONE COUNTED AFTER IT HAD COME APART: the lights ran 3.44s to 5.04s and the groups were
   together 1.76s to 4.0s, so tiles 4 and 5 lit with the × back between them. So: every tile's light
   — from the moment it starts to come up to the moment it has gone — sits inside the stretch where
   both groups are fully joined, and a⁵ is written no earlier than the fifth tile is counted.

   AND IT MOVED BY A NUMBER THAT IGNORED THE ×. 1.5rem, second group only: 1.1px between tiles 3 and
   4 against 4.4px elsewhere, 11px off centre. So the distance must be the formula, read off the
   rules, and the two groups must move by plus and minus half of it. */
function indexOwn_(L, m) {
  const rule = sel => rules.find(r => r.sel === sel && !isStill(r)) || { decls: {} };
  const shift = (rule('#splash-index').decls['--ix-shift'] || '').replace(/\s+/g, '');
  if (shift !== 'calc((2*var(--ix-out)+var(--ix-op)-var(--ix-in))/2)')
    fault(L.id, '--ix-shift is "' + shift + '", not half of (2 × the gap either side of the × + the × − the gap between tiles) — the joined row will not be evenly spaced');
  if (rule('.ix-line').decls.gap !== 'var(--ix-out)') fault(L.id, '.ix-line gap is not var(--ix-out) — the distance the groups close is computed from it');
  if (rule('.ix-g').decls.gap !== 'var(--ix-in)') fault(L.id, '.ix-g gap is not var(--ix-in) — the joined gap must match the gap between tiles');
  if (rule('.ix-op').decls.width !== 'var(--ix-op)') fault(L.id, '.ix-op width is not var(--ix-op) — the × must be as wide as the distance assumes');

  const name = sel => ((rule(sel).decls.animation || '').split(/\s+/).find(w => frames[w]));
  const window_ = (fr, isOn) => {
    // [the last key that is still off before it comes on, the first key that is off again after]
    if (!fr) return null;
    const keys = [];
    fr.forEach(st => st.keys.forEach(k => keys.push([k, isOn(st.decls)])));
    keys.sort((a, b) => a[0] - b[0]);
    const on = keys.filter(k => k[1]);
    if (!on.length) return null;
    const first = on[0][0], last = on[on.length - 1][0];
    const before = keys.filter(k => !k[1] && k[0] < first).map(k => k[0]);
    const after = keys.filter(k => !k[1] && k[0] > last).map(k => k[0]);
    return { from: before.length ? Math.max(...before) : first, to: after.length ? Math.min(...after) : last, first, last };
  };
  const shifted = d => /var\(--ix-shift\)/.test(d.transform || '');
  const g1 = window_(frames[name('.ix-g1')], shifted), g2 = window_(frames[name('.ix-g2')], shifted);
  if (!g1 || !g2) { fault(L.id, '.ix-g1 and .ix-g2 do not both move by --ix-shift — the groups never join'); return; }
  const joined = { from: Math.max(g1.first, g2.first), to: Math.min(g1.last, g2.last) };
  const lit = d => d.opacity === '1';
  const tiles = [...m.matchAll(/<i class="(ix-t\d+)">a<b class="ix-n">(\d+)<\/b><\/i>/g)];
  if (tiles.length !== 5 || tiles.some((t, k) => t[2] !== String(k + 1)))
    fault(L.id, 'does not number its five tiles 1 to 5 — the exponent is meant to be counted up to');
  let lastOn = 0;
  tiles.forEach(t => {
    const w = window_(frames[name('.' + t[1] + '::after, .' + t[1] + ' .ix-n')], lit);
    if (!w) { fault(L.id, '.' + t[1] + ' never lights — it is not counted'); return; }
    lastOn = Math.max(lastOn, w.from);
    if (w.from < joined.from || w.to > joined.to)
      fault(L.id, '.' + t[1] + ' is lit from ' + w.from + '% to ' + w.to + '% but the groups are joined only from '
        + joined.from + '% to ' + joined.to + '% — it is counted while they are apart');
  });
  const sum = window_(frames[name('.ix-sum')], lit);
  if (!sum) fault(L.id, '.ix-sum is not animated — a⁵ shows before anything has been counted');
  else if (sum.from < lastOn) fault(L.id, 'a⁵ is written at ' + sum.from + '%, before the fifth tile is counted at ' + lastOn + '%');
}

/* ---------- THE RING: ONE BOXER IS ONE BOXER, AND A SPARK IS A PUNCH THAT LANDED -------------------
   ASKED FOR AS "add a boxing animation loading. like boxing in the ring 8 bit." Four things the
   generic checks above cannot see, each of which still animates perfectly well:
     · EIGHT-BIT IS `step-end`. A pose that cross-fades or a boxer that glides between pixels is a
       modern animation in an old costume, so every animation here holds and jumps.
     · ONE POSE AT A TIME. Each boxer is three or four drawings swapped by opacity; at every moment
       of the loop exactly one of a boxer's drawings must be showing — two is a ghost, none is a
       boxer who blinks out of the ring.
     · A SPARK IS A PUNCH THAT LANDED. Spark 1 is blue's jab on gold, spark 2 gold's on blue; while
       either is lit, the one punching is in the jab and the one punched is in the hit. A spark
       over two boxers in their guard is a firework.
     · IT IS A RING: three ropes, two corner posts from the floor up, a bell, blue drawn mirrored to
       face gold, and pixels drawn with `crispEdges` — without it every square blurs at its edges
       and it stops being eight-bit. */
function boxOwn_(L, m, mine) {
  if (!/<svg class="bx-ring"[^>]*shape-rendering="crispEdges"/.test(m))
    fault(L.id, 'the ring is not drawn with shape-rendering="crispEdges" — the pixels blur at their edges');
  const ropes = (m.match(/class="bx-rope[ "]/g) || []).length;
  const posts = [...m.matchAll(/<rect class="bx-post"[^>]*height="(\d+)"/g)].filter(x => +x[1] >= 20).length;
  if (ropes !== 3) fault(L.id, 'has ' + ropes + ' ropes — a ring has three');
  if (posts !== 2) fault(L.id, 'has ' + posts + ' corner posts standing on the floor — the ring has two in view');
  if (!/class="bx-bell"/.test(m)) fault(L.id, 'has no bell');
  if (!/<g class="bx-r" transform="[^"]*scale\(-1 1\)"/.test(m)) fault(L.id, 'blue is not drawn mirrored — the two would face the same way');
  mine.filter(r => !isStill(r) && r.decls.animation && r.decls.animation !== 'none').forEach(r => {
    if (!/\bstep-end\b/.test(r.decls.animation)) fault(L.id, r.sel + ' is not step-end — it glides between pixels or fades between poses, which is not eight-bit');
  });
  /* THE VALUE A step-end ANIMATION HOLDS at t: the last stop at or before it. */
  const held = (name, prop, t) => {
    let at = -1, v = null;
    (frames[name] || []).forEach(s => s.keys.forEach(k => {
      if (k <= t && k >= at && s.decls[prop] !== undefined) { at = k; v = s.decls[prop]; }
    }));
    return v;
  };
  const POSES = { l: ['guard', 'jab', 'hit'], r: ['guard', 'jab', 'duck', 'hit'] };
  const who = side => side === 'l' ? 'gold' : 'blue';
  Object.keys(POSES).forEach(side => POSES[side].forEach(p => {
    if (!new RegExp('<g class="bx-pose bx-' + side + '-' + p + '"').test(m)) fault(L.id, 'has no ' + p + ' drawing for ' + who(side));
    if (!frames['bx-' + side + '-' + p]) fault(L.id, 'has no @keyframes bx-' + side + '-' + p);
  }));
  let ghosts = 0, gaps = 0;
  for (let t = 0; t < 100; t += 0.25) {
    Object.keys(POSES).forEach(side => {
      const on = POSES[side].filter(p => held('bx-' + side + '-' + p, 'opacity', t) === '1').length;
      if (on > 1) ghosts++;
      if (on < 1) gaps++;
    });
  }
  if (ghosts) fault(L.id, 'shows two drawings of one boxer at once at ' + ghosts + ' sampled moments — a ghost');
  if (gaps) fault(L.id, 'shows no drawing of a boxer at ' + gaps + ' sampled moments — a boxer who blinks out');
  [['1', 'r', 'l'], ['2', 'l', 'r']].forEach(([n, by, on]) => {
    let lit = 0, wrong = 0;
    for (let t = 0; t < 100; t += 0.25) {
      if (held('bx-spark-' + n, 'opacity', t) !== '1') continue;
      lit++;
      if (held('bx-' + by + '-jab', 'opacity', t) !== '1' || held('bx-' + on + '-hit', 'opacity', t) !== '1') wrong++;
    }
    if (!lit) fault(L.id, 'spark ' + n + ' never lights — nothing lands');
    if (wrong) fault(L.id, 'spark ' + n + ' is lit at ' + wrong + ' sampled moments when ' + who(by)
      + ' is not jabbing or ' + who(on) + ' is not hit — a spark over nothing');
  });
}

/* ---------- THE ANGLE AT THE CENTRE: P IS ON THE CIRCLE, AND THE ANGLE AT P IS HALF THE ONE AT O ----
   ASKED FOR AS "refine the circle theorems animation". Nothing in the markup says where P is — it is
   wherever the four keyframes put it — so P is re-derived from them: the end of chord A, the end of
   chord B and the vertex of the wedge must be one point, on the rim, at every stop AND half-way
   between stops (the browser interpolates translate, rotate and scale linearly, and a chord that
   cut inside the circle between samples would be a point leaving the arc). The wedge must open by
   half the centre angle and be turned to the bisector, which always points at M, the middle of arc
   AB; the label must stay the same distance from P. And the caption must name the theorem. */
function centOwn_(L, m) {
  const num = s => (String(s).match(/-?\d*\.?\d+/g) || []).map(Number);
  const rim = m.match(/<circle class="ct-rim" cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"/);
  if (!rim) { fault(L.id, 'has no .ct-rim circle to measure P against'); return; }
  const [cx, cy, r] = rim.slice(1).map(Number);
  const cen = m.match(/class="ct-cen" d="M([\d.]+) ([\d.]+) L([\d.]+) ([\d.]+) L([\d.]+) ([\d.]+)"/);
  if (!cen) { fault(L.id, 'has no .ct-cen path — the angle at the centre is not drawn'); return; }
  const [ax, ay, , , bx, by] = cen.slice(1).map(Number);
  const ang = (x, y) => Math.atan2(y, x) * 180 / Math.PI;
  const centre = ((ang(ax - cx, ay - cy) - ang(bx - cx, by - cy)) % 360 + 360) % 360;
  const mid = (ang(ax - cx, ay - cy) + ang(bx - cx, by - cy)) / 2;
  const M = [cx + r * Math.cos(mid * Math.PI / 180), cy + r * Math.sin(mid * Math.PI / 180)];
  const U = +((m.match(/class="ct-ch ct-a" x1="0" y1="0" x2="([\d.]+)"/) || [])[1] || 0);
  if (!U) { fault(L.id, 'the chords are not drawn from (0,0) along x — P cannot be derived'); return; }
  const wedge = (m.match(/class="ct-wedge" d="M0 0 L(-?[\d.]+) (-?[\d.]+) A[\d.]+ [\d.]+ 0 0 1 (-?[\d.]+) (-?[\d.]+) Z"/) || []).slice(1).map(Number);
  if (wedge.length !== 4) fault(L.id, 'the wedge at P is not drawn with its vertex at (0,0)');
  else {
    const open = ang(wedge[2], wedge[3]) - ang(wedge[0], wedge[1]);
    if (Math.abs(open - centre / 2) > 0.2) fault(L.id, 'the wedge at P opens ' + open.toFixed(1) + '° and the centre angle is ' + centre.toFixed(1) + '° — the edge angle must be half');
    if (Math.abs(ang(wedge[0], wedge[1]) + ang(wedge[2], wedge[3])) > 0.2) fault(L.id, 'the wedge at P is not symmetrical about +x, so turning it to the bisector puts it off the chords');
  }
  /* EACH STOP AS [key, translate x, y, rotate, scale] */
  const read = name => {
    const out = [];
    (frames[name] || []).forEach(st => st.keys.forEach(k => {
      const t = st.decls.transform || '';
      const tr = num((t.match(/translate\(([^)]*)\)/) || [])[1] || '0 0');
      const ro = num((t.match(/rotate\(([^)]*)\)/) || [])[1] || '0')[0];
      const sc = num((t.match(/scale\(([^)]*)\)/) || [])[1] || '1')[0];
      out.push([k, tr[0], tr[1], ro, sc]);
    }));
    return out.sort((a, b) => a[0] - b[0]);
  };
  const fa = read('ct-a'), fb = read('ct-b'), fw = read('ct-w'), fx = read('ct-x');
  if (!fa.length || !fb.length || !fw.length || !fx.length) { fault(L.id, 'is missing one of @keyframes ct-a, ct-b, ct-w, ct-x'); return; }
  const at = (fr, k) => {                     // linear, as the browser interpolates with `linear`
    let i = 0;
    while (i < fr.length - 1 && fr[i + 1][0] < k) i++;
    const a = fr[i], b = fr[Math.min(i + 1, fr.length - 1)];
    const u = b[0] === a[0] ? 0 : Math.max(0, Math.min(1, (k - a[0]) / (b[0] - a[0])));
    return a.map((v, j) => v + (b[j] - v) * u);
  };
  const end = q => [q[1] + q[4] * U * Math.cos(q[3] * Math.PI / 180), q[2] + q[4] * U * Math.sin(q[3] * Math.PI / 180)];
  const keys = new Set();
  [fa, fb, fw, fx].forEach(fr => fr.forEach((q, i) => { keys.add(q[0]); if (fr[i + 1]) keys.add((q[0] + fr[i + 1][0]) / 2); }));
  let off = 0, apart = 0, turned = 0, worst = 0, labD = null, labBad = 0, moved = new Set();
  [...keys].sort((a, b) => a - b).forEach(k => {
    const pa = end(at(fa, k)), pb = end(at(fb, k)), w = at(fw, k), x = at(fx, k);
    const d = Math.abs(Math.hypot(pa[0] - cx, pa[1] - cy) - r);
    worst = Math.max(worst, d);
    if (d > 0.3) off++;
    if (Math.hypot(pa[0] - pb[0], pa[1] - pb[1]) > 0.3 || Math.hypot(pa[0] - w[1], pa[1] - w[2]) > 0.3) apart++;
    const want = ang(M[0] - w[1], M[1] - w[2]);
    if (Math.abs(((w[3] - want) % 360 + 540) % 360 - 180) > 1) turned++;
    const ld = Math.hypot(x[1] - w[1], x[2] - w[2]);
    if (labD === null) labD = ld; else if (Math.abs(ld - labD) > 0.3) labBad++;
    moved.add(Math.round(pa[0] * 10));
  });
  if (off) fault(L.id, 'P leaves the circle at ' + off + ' sampled moments (worst ' + worst.toFixed(2) + ' units off the rim) — the chord does not reach the arc');
  if (apart) fault(L.id, 'the two chords and the wedge do not meet at one point at ' + apart + ' sampled moments — P comes apart');
  if (turned) fault(L.id, 'the wedge at P is not turned to the bisector (towards M, the middle of arc AB) at ' + turned + ' sampled moments');
  if (labBad) fault(L.id, 'the x label drifts away from P at ' + labBad + ' sampled moments');
  if (moved.size < 10) fault(L.id, 'P takes only ' + moved.size + ' places on the arc — it does not travel');
  if (!/angle at the centre/i.test(m) || !/twice/i.test(m)) fault(L.id, 'does not name the theorem — the caption must say the angle at the centre is twice the angle at the edge');
}

/* ---------- y = mx + c: THE LINE GOES THROUGH (0, c), AND THE NUMBER IS THE SLOPE ---------------------
   ASKED FOR AS "refine the gradiant animation". The old one rocked a bar between two angles nobody
   named; its pivot and its dot were two sets of numbers 0.4px apart, and its end ran out past the
   axes. Nothing in the markup says where the line is — it is wherever `@keyframes mx-line` puts it
   — so, as for the angle at the centre, the picture is re-derived from the keyframes:

     · (0, c) IS ONE POINT. The dot sits on the y-axis, above the x-axis, and every stop of the line,
       the triangle and (one square along) the rise is carried to it — so the browser, interpolating
       a translate between equal values, puts the line through (0, c) at every frame.
     · RUN 1, RISE m, ON THE LINE. The run is one square of the grid; the triangle is a unit right
       triangle stretched by m; at every sampled moment (stops, half-way, and every 0.2%) its top
       corner and the top of the rise are one point, on the line.
     · THE NUMBER IS THE SLOPE. Each value under the drawing is fully up only while the line holds
       at exactly that gradient, for long enough to read; never two at once; the rise's own label
       says the same value, on the same clock, beside the middle of the rise.
     · NO WORD IS CROSSED. Every label, while it is showing, stays clear of the line, the rise, the
       run and the axes — measured as boxes in the mono face against strokes of their real width.
       c is the exception that proves it: it is written ON its dot, which is drawn over the line.
     · THE STILL IS ONE CLEAR PICTURE: under reduced motion exactly one value is up and the line,
       triangle and rise all agree with it.

   And three that the review of the first build found by looking, each now a sentence here:
     · ONE WAY ROUND, AND NO LURCH. The first build swung from m = 2 back to m = -1 — 108° at 189°/s,
       back through four stops it had just named, against 60-86°/s for every step. The line's turn
       may never reverse, and never run faster than 100°/s between two keyframes. Going on over the
       top means passing through vertical, where m has no value: the triangle, run and rise
       (`.mx-rr`) are faded out there, and the corner-on-the-line sentence is asked only while they
       show; they must be clipped to the plot, because they ride up past it as they fade.
     · A HALF IS BUILT, NEVER THE ½ GLYPH. Cascadia's ½ is two digits and a slash in one character
       cell; at 320@1x its digits were 5.5px against 13px for the whole numbers beside the other
       rises. A built half is a digit above a bar and a digit below it, centred on it, at no less
       than 85% of the whole numbers' size, and it may sit anywhere BESIDE its rise rather than by
       its middle — the stack is taller than a half-unit rise.
     · NO BARE "=". The caption read "m = rise ÷ run =" with nothing after it for 18.5% of the loop.
       The "=" belongs inside each value's cell, so it fades with the value. */
function mxcOwn_(L, m) {
  m = m.replace(/<!--[\s\S]*?-->/g, '');      // the generator's notes are not part of the picture
  const num = s => (String(s).match(/-?\d*\.?\d+(?:e-?\d+)?/g) || []).map(Number);
  const attr = (s, n) => { const q = s.match(new RegExp('\\s' + n + '="([^"]*)"')); return q ? q[1] : null; };
  const el = (tag, cls) => {
    const re = new RegExp('<' + tag + '\\b([^>]*\\sclass="(?:[^"]*\\s)?' + cls + '(?:\\s[^"]*)?"[^>]*)>');
    const q = m.match(re); return q ? q[1] : null;
  };
  const dot = el('circle', 'mx-dot'), ax = el('line', 'mx-ax'), ay = el('line', 'mx-ay');
  if (!dot || !ax || !ay) { fault(L.id, 'has no .mx-dot, .mx-ax or .mx-ay — there is no (0, c) to measure against'); return; }
  const P = [+attr(dot, 'cx'), +attr(dot, 'cy')], R0 = +attr(dot, 'r');
  const x0 = +attr(ay, 'x1'), y0 = +attr(ax, 'y1');
  if (Math.abs(P[0] - x0) > 0.01) fault(L.id, 'the point the line turns about is at x = ' + P[0] + ', not on the y-axis at ' + x0 + ' — that is not (0, c)');
  if (!(P[1] < y0 - 1)) fault(L.id, 'the point the line turns about is not above the x-axis — c is meant to be a height you can see');

  /* ONE SQUARE OF THE GRID IS ONE UNIT, and nothing else here says how long "1" is. */
  const grid = (m.match(/class="mx-grid" d="([^"]+)"/) || [])[1] || '';
  const gx = [...grid.matchAll(/M(-?[\d.]+) [\d.]+V/g)].map(q => +q[1]).concat([x0]).sort((a, b) => a - b);
  const steps = gx.slice(1).map((v, i) => v - gx[i]).filter(d => d > 0.01);
  const u = steps.length ? Math.min(...steps) : 0;
  if (!u) { fault(L.id, 'has no vertical grid lines — there is no square to call one unit'); return; }
  if (steps.some(d => Math.abs(d / u - Math.round(d / u)) > 0.01)) fault(L.id, 'its grid lines are not evenly spaced — a square is not one unit');

  const run = el('line', 'mx-run');
  if (!run) fault(L.id, 'has no .mx-run — the triangle has no run');
  else if (Math.abs(+attr(run, 'x1') - P[0]) > 0.01 || Math.abs(+attr(run, 'y1') - P[1]) > 0.01
        || Math.abs(+attr(run, 'x2') - P[0] - u) > 0.01 || Math.abs(+attr(run, 'y2') - P[1]) > 0.01)
    fault(L.id, 'the run is not one square along from (0, c) — "run 1" would be a different length from the grid');
  const tri = (m.match(/class="mx-tri" d="M0 0 H(-?[\d.]+) V(-?[\d.]+) Z"/) || []).slice(1).map(Number);
  if (tri.length !== 2 || Math.abs(tri[0] - u) > 0.01 || Math.abs(tri[1] + u) > 0.01)
    fault(L.id, 'the triangle is not drawn as run 1, rise 1 from (0,0) — stretching it by m would not give rise m');
  const rise = el('line', 'mx-rise');
  const RL = rise ? -(+attr(rise, 'y2')) : 0;
  if (!rise || +attr(rise, 'x1') || +attr(rise, 'y1') || +attr(rise, 'x2') || !(RL > 0))
    { fault(L.id, 'the rise is not drawn upright from (0,0) — its length cannot be read off its scale'); return; }
  const lineEl = el('line', 'mx-line');
  if (!lineEl || +attr(lineEl, 'y1') || +attr(lineEl, 'y2') || Math.abs(+attr(lineEl, 'x1') + +attr(lineEl, 'x2')) > 0.01)
    { fault(L.id, 'the line is not drawn along x through (0,0) — where it goes cannot be derived from its turn'); return; }
  const clip = m.match(/<clipPath id="mx-clip"><rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"\/>/);
  /* THE CLIPPED GROUP IS ONE LINE OF MARKUP, as the generator writes it, so `.` stops at its end. */
  const clipped = (m.match(/<g clip-path="url\(#mx-clip\)">(.*)<\/g>/) || [])[1] || '';
  if (!clip || !/class="mx-line"/.test(clipped))
    { fault(L.id, 'the line is not clipped to the plot — it runs out past the axes, which is what the old one did'); return; }
  if (!/class="mx-tri"/.test(clipped) || !/class="mx-rise"/.test(clipped))
    fault(L.id, 'the triangle and the rise are not clipped to the plot — past m = 2 they ride up the line and out of the top of the plot while they fade');
  /* THE TRIANGLE, RUN AND RISE FADE AS ONE, through the middle of the swing over the top. */
  const rrBody = (m.match(/<g class="mx-rr">(.*?)<\/g>/) || [])[1] || '';
  if (!/class="mx-tri"/.test(rrBody) || !/class="mx-rise"/.test(rrBody) || !/class="mx-run"/.test(rrBody))
    fault(L.id, 'the triangle, the run and the rise are not one .mx-rr group — they cannot fade together while the line goes through vertical');
  const box = clip.slice(1).map(Number), CLIP = [box[0], box[1], box[0] + box[2], box[1] + box[3]];

  /* ---- THE KEYFRAMES, AS [key, tx, ty, rotate, sx, sy] ---- */
  /* THE LAST RULE NAMING `sel` THAT SETS `prop` — `.mx-line` has one rule for its stroke and another
     for its motion, and the first of them has no animation in it. */
  const decl = (sel, prop) => {
    const r = rules.filter(r => !isStill(r) && parts(r.sel).includes(sel) && r.decls[prop] !== undefined).pop();
    return r ? r.decls[prop] : '';
  };
  const nameOf = sel => (decl(sel, 'animation').split(/\s+/).find(w => frames[w]));
  const tf = t => {
    const tr = num((t.match(/translate\(([^)]*)\)/) || [])[1] || '0 0');
    const sc = num((t.match(/scale\(([^)]*)\)/) || [])[1] || '1');
    return [tr[0], tr[1] || 0, num((t.match(/rotate\(([^)]*)\)/) || [])[1] || '0')[0], sc[0], sc.length > 1 ? sc[1] : sc[0]];
  };
  const read = (name, prop) => {
    const out = [];
    (frames[name] || []).forEach(st => st.keys.forEach(k => {
      if (st.decls[prop] === undefined) return;
      out.push([k].concat(prop === 'opacity' ? [parseFloat(st.decls.opacity)] : tf(st.decls.transform)));
    }));
    return out.sort((a, b) => a[0] - b[0]);
  };
  const at = (fr, k) => {                     // linear, as the browser interpolates with `linear`
    let i = 0;
    while (i < fr.length - 1 && fr[i + 1][0] < k) i++;
    const a = fr[i], b = fr[Math.min(i + 1, fr.length - 1)];
    const w = b[0] === a[0] ? 0 : Math.max(0, Math.min(1, (k - a[0]) / (b[0] - a[0])));
    return a.map((v, j) => v + (b[j] - v) * w);
  };
  const fl = read(nameOf('.mx-line'), 'transform'), ft = read(nameOf('.mx-tri'), 'transform'),
        fr = read(nameOf('.mx-rise'), 'transform');
  if (!fl.length || !ft.length || !fr.length) { fault(L.id, 'one of .mx-line, .mx-tri, .mx-rise has no transform keyframes — nothing to derive the picture from'); return; }
  const dur = parseFloat((decl('.mx-line', 'animation').match(/(\d*\.?\d+)s\b/) || [])[1]);
  if (!(dur >= 8 && dur <= 10)) fault(L.id, 'loops every ' + dur + 's — it was asked for as an 8 to 10 second loop');
  /* HOW MUCH OF THE TRIANGLE, RUN AND RISE SHOWS at t — 1 throughout if `.mx-rr` never fades. */
  const fo = nameOf('.mx-rr') ? read(nameOf('.mx-rr'), 'opacity') : [];
  const shows = t => fo.length ? at(fo, t)[1] : 1;

  /* ---- ONE WAY ROUND, AND NO LURCH ---- */
  let cw = 0, acw = 0, fastest = 0, fastAt = 0;
  for (let i = 1; i < fl.length; i++) {
    const d = fl[i][3] - fl[i - 1][3], dt = (fl[i][0] - fl[i - 1][0]) / 100 * dur;
    if (d > 1e-6) cw++;
    if (d < -1e-6) acw++;
    if (dt > 0 && Math.abs(d) / dt > fastest) { fastest = Math.abs(d) / dt; fastAt = fl[i][0]; }
  }
  if (cw && acw) fault(L.id, 'the line turns one way at ' + acw + ' keyframes and back the other at ' + cw
    + ' — it runs back through gradients it has just named, which is the rewind the first build had');
  if (fastest > 100) fault(L.id, 'the line turns at ' + Math.round(fastest) + '°/s at ' + fastAt
    + '% — over 100°/s; the steps between named gradients peak near 84, and the first build\'s 189°/s swing back was the one jolt in the loop');

  /* ---- (0, c) IS ONE POINT, IN EVERY KEYFRAME ---- */
  const near = (a, b, e) => Math.abs(a - b) <= (e || 0.01);
  const offP = fl.filter(q => !near(q[1], P[0]) || !near(q[2], P[1])).length;
  if (offP) fault(L.id, 'the line is carried somewhere other than (0, c) at ' + offP + ' keyframes — it turns about a point that is not where it cuts');
  if (ft.some(q => !near(q[1], P[0]) || !near(q[2], P[1]) || !near(q[4], 1))) fault(L.id, 'the triangle does not start at (0, c), or is stretched sideways — the run would not be 1');
  if (fr.some(q => !near(q[1], P[0] + u) || !near(q[2], P[1]) || !near(q[4], 1))) fault(L.id, 'the rise is not one square along from (0, c) — it does not stand at the end of the run');

  /* ---- THE NUMBERS ---- */
  const val = s => {
    const t = s.replace(/<span class="mx-fr"><b>(\d+)<\/b><b>(\d+)<\/b><\/span>/g, '$1/$2').replace(/<[^>]+>/g, '')
               .replace(/−/g, '-').replace(/½/g, '1/2').trim();
    const q = t.match(/^(-?)(\d+)(?:\/(\d+))?$/);
    return q ? (q[1] ? -1 : 1) * (+q[2]) / (q[3] ? +q[3] : 1) : NaN;
  };
  const glyph = m.replace(/<[^>]+>/g, '').match(/[½⅓⅔¼¾⅕⅖⅗⅘⅙⅚⅛⅜⅝⅞]/);
  if (glyph) fault(L.id, 'writes a fraction as the ' + glyph[0] + ' glyph — two digits and a slash in one character cell, about 5.5px tall at 320@1x; build it, a digit over a bar over a digit');

  /* THE CAPTION: "m = rise ÷ run", then one cell holding every value, each with its own "=". */
  const say = (m.match(/<div class="mx-say">([\s\S]*?)<\/div>/) || [])[1] || '';
  if (/=\s*$/.test(say.split('<span class="mx-vals">')[0].replace(/<[^>]+>/g, '')))
    fault(L.id, 'the caption\'s "=" is outside the values, so between stops it reads "m = rise ÷ run =" with nothing after it');
  const bare = [];
  const says = [...m.matchAll(/<i class="mx-v (mx-k\d+)">([\s\S]*?)<\/i>/g)].map(q => {
    if (!/^\s*=/.test(q[2].replace(/<[^>]+>/g, ''))) bare.push('.' + q[1]);
    return { k: q[1], v: val(q[2].replace(/^((?:\s|<[^>]+>)*)=/, '$1')) };
  });
  if (bare.length) fault(L.id, 'the value' + (bare.length > 1 ? 's in ' : ' in ') + bare.join(', ') + ' carr' + (bare.length > 1 ? 'y' : 'ies')
    + ' no "=" of ' + (bare.length > 1 ? 'their' : 'its') + ' own — the "=" must fade with the value, or the caption ends in a bare "=" between stops');

  /* THE WORDS IN THE DRAWING: each <text> on its own, and each group of them (a built fraction) as one
     word that fades as one — its classes, its texts and its bar. */
  const textsIn = (s, off) => [...s.matchAll(/<text class="(mx-lab[^"]*)" x="([\d.]+)" y="([\d.]+)">([^<]*)<\/text>/g)]
    .map(q => ({ cls: q[1].split(/\s+/), x: +q[2], y: +q[3], text: q[4], at: off + q.index }));
  const groups = [...m.matchAll(/<g class="([^"]+)">((?:(?!<\/?g\b)[\s\S])*?)<\/g>/g)]
    .filter(q => /<text\b/.test(q[2]))
    .map(q => ({ cls: q[1].split(/\s+/), at: q.index, end: q.index + q[0].length, body: q[2], off: q.index + q[0].indexOf('>') + 1 }));
  const words = textsIn(m, 0).filter(t => !groups.some(g => t.at > g.at && t.at < g.end))
    .map(t => ({ cls: t.cls, parts: [t], bar: null }))
    .concat(groups.map(g => {
      const b = g.body.match(/<line class="mx-fb" x1="([\d.]+)" y1="([\d.]+)" x2="([\d.]+)" y2="([\d.]+)"/);
      return { cls: g.cls, parts: textsIn(g.body, g.off), bar: b ? b.slice(1).map(Number) : null };
    }));
  const kOf = w => w.cls.find(c => /^mx-k\d+$/.test(c));
  const styleOf = cls => {                      // the later rule wins, as in the cascade, for one class
    const o = {};
    rules.filter(r => !isStill(r) && parts(r.sel).some(p => cls.includes(p.replace(/^\./, '')) && /^\.[\w-]+$/.test(p)))
      .forEach(r => {
        if (r.decls.font) { const q = r.decls.font.match(/(\d*\.?\d+)px/); if (q) o.size = +q[1]; }
        if (r.decls['font-size']) o.size = parseFloat(r.decls['font-size']);
        if (r.decls['text-anchor']) o.anchor = r.decls['text-anchor'];
        if (r.decls['stroke-width']) o.sw = parseFloat(r.decls['stroke-width']);
        if (r.decls.animation) o.anim = r.decls.animation.split(/\s+/).find(w => frames[w]);
      });
    return o;
  };
  /* A WORD'S BOX: each text as a mono-face box at its own size and anchor, and the bar with its stroke. */
  const swBar = styleOf(['mx-fb']).sw || 1;
  words.forEach(w => {
    const bs = w.parts.map(p => {
      const st = styleOf(p.cls), z = st.size || 8, wd = p.text.length * 0.6 * z, h = 0.72 * z;
      p.size = z;
      const x1 = p.x - (st.anchor === 'start' ? 0 : st.anchor === 'end' ? wd : wd / 2);
      return [x1, p.y - h / 2, x1 + wd, p.y + h / 2];
    });
    if (w.bar) bs.push([w.bar[0], w.bar[1] - swBar / 2, w.bar[2], w.bar[3] + swBar / 2]);
    w.box = [Math.min(...bs.map(b => b[0])), Math.min(...bs.map(b => b[1])), Math.max(...bs.map(b => b[2])), Math.max(...bs.map(b => b[3]))];
  });
  /* A BUILT FRACTION READ AS DRAWN: one digit above the bar and one below, both centred on it, and a
     minus (if any) in front of it at its height. Anything else is not a fraction, and says NaN. */
  const fracVal = w => {
    const [x1, yb, x2] = w.bar, mid = (x1 + x2) / 2;
    const up = w.parts.filter(p => p.y < yb && Math.abs(p.x - mid) < 0.5);
    const dn = w.parts.filter(p => p.y > yb && Math.abs(p.x - mid) < 0.5);
    const minus = w.parts.filter(p => p.text === '−' && p.x < x1 && Math.abs(p.y - yb) < 0.5);
    if (up.length !== 1 || dn.length !== 1 || up.length + dn.length + minus.length !== w.parts.length) return NaN;
    return (minus.length ? -1 : 1) * val(up[0].text) / val(dn[0].text);
  };
  const rls = words.filter(w => kOf(w)).map(w => ({ k: kOf(w), w,
    v: w.bar ? fracVal(w) : val(w.parts.slice().sort((a, b) => a.x - b.x).map(p => p.text).join('')) }));
  if (says.length < 5 || says.some(s => isNaN(s.v))) { fault(L.id, 'has ' + says.length + ' values of m under the drawing, or one that does not read as a number'); return; }
  const vs = says.map(s => s.v);
  if (new Set(vs).size !== vs.length) fault(L.id, 'names the same gradient twice');
  if (!vs.some(v => v < 0) || !vs.includes(0) || !vs.some(v => v > 1) || !vs.some(v => v !== Math.round(v)))
    fault(L.id, 'its gradients (' + vs.join(', ') + ') do not take in a falling line, a flat one, a steep one and a fraction');
  const ops = says.map(s => read(nameOf('.' + s.k), 'opacity'));
  says.forEach((s, i) => { if (!ops[i].length) fault(L.id, 'm = ' + s.v + ' (.' + s.k + ') never fades — it is up all the time or never'); });

  /* EVERY KEYFRAME STOP, EVERY HALF-WAY BETWEEN, AND EVERY 0.2% — the stops alone would never see what
     the browser draws between them, which is where a linear turn and a linear stretch part. */
  const keys = new Set();
  [fl, ft, fr].concat(ops).forEach(f => f.forEach((q, i) => { keys.add(q[0]); if (f[i + 1]) keys.add((q[0] + f[i + 1][0]) / 2); }));
  for (let k = 0; k <= 100; k += 0.2) keys.add(Math.round(k * 10) / 10);
  const T = [...keys].sort((a, b) => a - b);
  const rad = d => d * Math.PI / 180;
  const slope = q => -Math.tan(rad(q[3]));
  const offLine = (q, pt) => Math.abs(-(pt[0] - q[1]) * Math.sin(rad(q[3])) + (pt[1] - q[2]) * Math.cos(rad(q[3])));
  let apart = 0, gapWorst = 0, crowd = 0, wrong = [], up = says.map(() => 0);
  T.forEach(t => {
    const l = at(fl, t), tr_ = at(ft, t), ri = at(fr, t);
    const corner = [tr_[1] + u, tr_[2] - tr_[5] * u], top = [ri[1], ri[2] - ri[5] * RL];
    const d = Math.max(offLine(l, corner), Math.hypot(corner[0] - top[0], corner[1] - top[1]));
    /* ASKED ONLY WHILE THEY SHOW. Through vertical the triangle and rise are carried straight across,
       unseen, from the m they faded out at to the m they fade in at — nowhere near the line. */
    if (shows(t) > 0.001) {
      gapWorst = Math.max(gapWorst, d);
      if (d > 0.35) apart++;
    }
    let sum = 0;
    says.forEach((s, i) => {
      const o = ops[i].length ? at(ops[i], t)[1] : 0;
      sum += o;
      if (o > 0.999) {
        up[i]++;
        const ms = slope(l), mt = tr_[5], mr = ri[5] * RL / u;
        if (!near(ms, s.v, 0.005) || !near(mt, s.v, 0.005) || !near(mr, s.v, 0.005))
          wrong.push('m = ' + s.v + ' is up at ' + t + '% while the line is at ' + ms.toFixed(3) + ', the triangle '
            + mt.toFixed(3) + ', the rise ' + mr.toFixed(3));
      }
    });
    if (sum > 1.001) crowd++;
  });
  if (apart) fault(L.id, 'the triangle\'s corner, the top of the rise and the line part at ' + apart + ' sampled moments (worst ' + gapWorst.toFixed(2) + ' units) — rise m does not reach the line');
  if (wrong.length) fault(L.id, 'shows a number that is not the slope at ' + wrong.length + ' sampled moments, first: ' + wrong[0]);
  if (crowd) fault(L.id, 'shows two values of m at once at ' + crowd + ' sampled moments');
  const step = 100 / T.length;
  says.forEach((s, i) => {
    /* FULLY UP FOR 8% OF THE LOOP — 0.8s at 10s, long enough to read two characters. Counted on the
       0.2% grid only, so the extra stop and half-way keys do not inflate it. */
    const n = T.filter(t => Math.abs(t * 5 - Math.round(t * 5)) < 1e-9 && ops[i].length && at(ops[i], t)[1] > 0.999).length * 0.2;
    if (n < 8) fault(L.id, 'm = ' + s.v + ' is fully up for ' + n.toFixed(1) + '% of the loop — not long enough to read');
    const r = rls.find(x => x.k === s.k);
    if (!s.v) return;                                            // a flat line has no rise to label
    if (!r) { fault(L.id, 'm = ' + s.v + ' has no label on its rise'); return; }
    if (!near(r.v, s.v, 1e-9)) fault(L.id, 'the rise is labelled ' + (isNaN(r.v) ? 'with something that is not a number, or not a built fraction,' : r.v) + ' while the caption says m = ' + s.v);
    /* BESIDE ITS RISE: starting just right of it, and centred somewhere between its foot and its top. A
       whole number sits by the middle; a built half is taller than its half-unit rise and sits by the
       foot, where the line arriving at it does not run through it. */
    const bx = r.w.box, cy = (bx[1] + bx[3]) / 2, foot = P[1], tip = P[1] - s.v * u;
    if (bx[0] < P[0] + u + 1 || bx[0] > P[0] + u + 6 || cy < Math.min(foot, tip) - 0.01 || cy > Math.max(foot, tip) + 0.01)
      fault(L.id, 'the label ' + r.v + ' is not beside its rise (box ' + bx.map(v => +v.toFixed(2)).join(' ') + ')');
    /* AND NO SMALLER THAN THE WHOLE NUMBERS, near enough. */
    const whole = rls.filter(x => !x.w.bar).map(x => Math.min(...x.w.parts.map(p => p.size)));
    const least = Math.min(...r.w.parts.map(p => p.size));
    if (whole.length && least < 0.85 * Math.max(...whole))
      fault(L.id, 'the label ' + r.v + ' is set at ' + least + ', under 85% of the whole numbers\' ' + Math.max(...whole) + ' — the number the splash is about, in its smallest type');
  });

  /* ---- NO WORD IS CROSSED WHILE IT SHOWS ---- */
  const segBox = (a, b, bx) => {
    let t0 = 0, t1 = 1, hit = true;
    const dx = b[0] - a[0], dy = b[1] - a[1];
    [[-dx, a[0] - bx[0]], [dx, bx[2] - a[0]], [-dy, a[1] - bx[1]], [dy, bx[3] - a[1]]].forEach(([p, q]) => {
      if (!p) { if (q < 0) hit = false; return; }
      const r = q / p; if (p < 0) t0 = Math.max(t0, r); else t1 = Math.min(t1, r);
    });
    if (hit && t0 <= t1) return 0;
    const L2 = dx * dx + dy * dy;
    const pd = c => { const w = L2 ? Math.max(0, Math.min(1, ((c[0] - a[0]) * dx + (c[1] - a[1]) * dy) / L2)) : 0;
                      return Math.hypot(c[0] - a[0] - w * dx, c[1] - a[1] - w * dy); };
    const bd = c => Math.hypot(Math.max(bx[0] - c[0], 0, c[0] - bx[2]), Math.max(bx[1] - c[1], 0, c[1] - bx[3]));
    return Math.min(pd([bx[0], bx[1]]), pd([bx[2], bx[1]]), pd([bx[0], bx[3]]), pd([bx[2], bx[3]]), bd(a), bd(b));
  };
  const clipLine = q => {
    const d = [Math.cos(rad(q[3])), Math.sin(rad(q[3]))];
    let lo = -1e3, hi = 1e3;
    [0, 1].forEach(j => {
      if (Math.abs(d[j]) < 1e-12) return;
      const r0 = (CLIP[j] - q[1 + j]) / d[j], r1 = (CLIP[j + 2] - q[1 + j]) / d[j];
      lo = Math.max(lo, Math.min(r0, r1)); hi = Math.min(hi, Math.max(r0, r1));
    });
    return [[q[1] + lo * d[0], q[2] + lo * d[1]], [q[1] + hi * d[0], q[2] + hi * d[1]]];
  };
  const sw = cls => styleOf(cls).sw || 1;
  const fixed = [['the x-axis', [[+attr(ax, 'x1'), y0], [+attr(ax, 'x2'), y0]], sw(['mx-ax'])],
                 ['the y-axis', [[x0, +attr(ay, 'y1')], [x0, +attr(ay, 'y2')]], sw(['mx-ay'])]];
  const runSeg = run ? ['the run', [[+attr(run, 'x1'), +attr(run, 'y1')], [+attr(run, 'x2'), +attr(run, 'y2')]], sw(['mx-run'])] : null;
  /* READ ONCE: `styleOf` walks every rule in the sheet, and asking it per label per sampled moment made
     this check twenty seconds long. */
  const swLine = sw(['mx-line']), swRise = sw(['mx-rise']);
  const crossed = [];
  words.forEach(wd_ => {
    const [q] = wd_.parts, cls = wd_.cls;
    if (!wd_.bar && wd_.parts.length === 1 && near(q.x, P[0]) && near(q.y, P[1])) {
      /* c, ON ITS DOT. Clear of nothing and needing to be: the dot is drawn after the line, so it covers
         it, and the letter must fit inside the dot. */
      const s = styleOf(cls).size || 8;
      if (m.indexOf('class="mx-dot"') < m.indexOf('class="mx-line"')) fault(L.id, 'the dot is drawn under the line — c, written on it, is crossed');
      if (Math.hypot(0.3 * s, 0.36 * s) > R0) fault(L.id, 'c does not fit inside its dot');
      return;
    }
    const text = wd_.parts.map(p => p.text).join(wd_.bar ? '/' : ''), bx = wd_.box;
    const st = styleOf(cls), of = st.anim ? read(st.anim, 'opacity') : [];
    T.forEach(t => {
      if (of.length && at(of, t)[1] < 0.25) return;
      const l = at(fl, t), ri = at(fr, t);
      const near_ = [['the line', clipLine(l), swLine]].concat(fixed);
      /* THE RISE AND THE RUN COUNT WHILE THEY SHOW — through vertical they are faded out and the rise is
         being carried straight across, unseen. */
      if (shows(t) > 0.001) near_.push(['the rise', [[ri[1], ri[2]], [ri[1], ri[2] - ri[5] * RL]], swRise]);
      if (shows(t) > 0.001 && runSeg) near_.push(runSeg);
      near_.forEach(([nm, sg, wdt]) => {
        const g = segBox(sg[0], sg[1], bx) - wdt / 2;
        if (g < 0.8) crossed.push('"' + text + '" (' + cls.filter(c => c !== 'mx-lab').join(' ') + ') by ' + nm + ' at ' + t + '%, ' + g.toFixed(2) + ' clear');
      });
    });
  });
  if (crossed.length) fault(L.id, 'a word is crossed or touched while it shows, at ' + crossed.length + ' sampled moments, first: ' + crossed[0]);

  /* ---- THE STILL ---- */
  const base = sel => tf(decl(sel, 'transform'));
  const shown = says.filter(s => parseFloat(decl('.' + s.k, 'opacity')) === 1);
  if (shown.length !== 1) fault(L.id, 'under reduced motion ' + shown.length + ' values of m are up — the still must show exactly one');
  else {
    const v = shown[0].v, bl = base('.mx-line'), bt = base('.mx-tri'), br = base('.mx-rise');
    if (!(v > 0)) fault(L.id, 'the still is m = ' + v + ' — a still with no rising triangle is not the clear picture');
    if (!near(-Math.tan(rad(bl[2])), v, 0.005) || !near(bt[4], v, 0.005) || !near(br[4] * RL / u, v, 0.005)
        || !near(bl[0], P[0]) || !near(bl[1], P[1]))
      fault(L.id, 'the still says m = ' + v + ' but its line, triangle or rise is drawn at another gradient, or off (0, c)');
    const rr = decl('.mx-rr', 'opacity');
    if (rr !== '' && parseFloat(rr) !== 1) fault(L.id, 'under reduced motion .mx-rr is at opacity ' + rr + ' — the still\'s triangle, run and rise are hidden');
  }

  if (!/y = <b class="mx-tm">m<\/b>x \+ <b class="mx-tc">c<\/b>/.test(m) || !/rise ÷ run/.test(m))
    fault(L.id, 'the caption does not say y = mx + c and m = rise ÷ run');
  said.push('#splash-mxc: m = ' + vs.join(', ') + '; corner and rise within ' + gapWorst.toFixed(3) + ' of the line; turns one way, at most '
    + Math.round(fastest) + '°/s');
}

console.log('\nTHE SPLASHES THAT ARE ONE SEAMLESS LOOP  (' + LOOPS.length + ')');
said.forEach(s => console.log('  ' + s));
if (faults.length) {
  console.log('\nFAULTS  (' + faults.length + ')');
  faults.forEach(f => console.log('  ' + f));
  process.exit(1);
}
console.log('\nOK — every one loops without a seam, on one clock, moving only transform and opacity, centred.');
